static bool common_speculative_are_compatible(
    const llama_model * model_tgt,
    const llama_model * model_dft) {
    const llama_vocab * vocab_tgt = llama_model_get_vocab(model_tgt);
    const llama_vocab * vocab_dft = llama_model_get_vocab(model_dft);

    const auto vocab_type_tgt = llama_vocab_type(vocab_tgt);
    SPC_DBG("vocab_type tgt: %d\n", vocab_type_tgt);

    const auto vocab_type_dft = llama_vocab_type(vocab_dft);
    SPC_DBG("vocab_type dft: %d\n", vocab_type_dft);

    if (vocab_type_tgt != vocab_type_dft) {
        SPC_WRN("draft model vocab type must match target model to use speculation but "
                "vocab_type_dft = %d while vocab_type_tgt = %d\n", vocab_type_dft, vocab_type_tgt);
        return false;
    }

    if (llama_vocab_get_add_bos(vocab_tgt) != llama_vocab_get_add_bos(vocab_dft) ||
        (llama_vocab_get_add_bos(vocab_tgt) && llama_vocab_bos(vocab_tgt) != llama_vocab_bos(vocab_dft))) {
        SPC_WRN("draft model bos tokens must match target model to use speculation. add: %d - %d, id: %d - %d)\n",
                llama_vocab_get_add_bos(vocab_tgt), llama_vocab_get_add_bos(vocab_dft),
                llama_vocab_bos(vocab_tgt), llama_vocab_bos(vocab_dft));
        return false;
    }

    if (llama_vocab_get_add_eos(vocab_tgt) != llama_vocab_get_add_eos(vocab_dft) ||
        (llama_vocab_get_add_eos(vocab_tgt) && llama_vocab_eos(vocab_tgt) != llama_vocab_eos(vocab_dft))) {
        SPC_WRN("draft model eos tokens must match target model to use speculation. add: %d - %d, id: %d - %d)\n",
                llama_vocab_get_add_eos(vocab_tgt), llama_vocab_get_add_eos(vocab_dft),
                llama_vocab_eos(vocab_tgt), llama_vocab_eos(vocab_dft));
        return false;
    }

    {
        const int n_vocab_tgt = llama_vocab_n_tokens(vocab_tgt);
        const int n_vocab_dft = llama_vocab_n_tokens(vocab_dft);
        const int vocab_diff  = n_vocab_tgt > n_vocab_dft
            ? n_vocab_tgt - n_vocab_dft
            : n_vocab_dft - n_vocab_tgt;

        if (vocab_diff > SPEC_VOCAB_MAX_SIZE_DIFFERENCE) {
            SPC_DBG("draft model vocab must closely match target model to use speculation but "
                    "target vocab size %d does not match draft vocab size %d - difference %d, max allowed %d\n",
                    n_vocab_tgt, llama_vocab_n_tokens(vocab_dft), vocab_diff, SPEC_VOCAB_MAX_SIZE_DIFFERENCE);
            return false;
        }

        for (int i = SPEC_VOCAB_CHECK_START_TOKEN_ID; i < std::min(n_vocab_tgt, n_vocab_dft); ++i) {
            const char * token_text_tgt = llama_vocab_get_text(vocab_tgt, i);
            const char * token_text_dft = llama_vocab_get_text(vocab_dft, i);

            if (std::strcmp(token_text_tgt, token_text_dft) != 0) {
                SPC_DBG("draft model vocab must match target model to use speculation but "
                        "token %d content differs - target '%s', draft '%s'\n", i,
                        common_token_to_piece(vocab_tgt, i).c_str(),
                        common_token_to_piece(vocab_dft, i).c_str());
                return false;
            }
        }
    }

    return true;
}

using common_speculative_draft_params_vec = std::vector<common_speculative_draft_params>;

// state of an implementation of speculative decoding
//
// each implementation has a unique type and a state that is implementation-specific
// in a subclass of common_speculative_impl
struct common_speculative_impl {
    const common_speculative_type type;

    uint32_t n_seq;
    int32_t n_max; // maximum draft length after implementation-specific limits

    size_t n_call_begin  = 0; // number of times this implementation was called for refresh.
    size_t n_call_draft  = 0; // number of times this implementation was called for generation.
    size_t n_call_accept = 0; // number of times this implementation was called for accumulation.

    size_t n_gen_drafts = 0; // number of times a draft or part was generated by this implementation.
    size_t n_acc_drafts = 0; // number of times a draft or part was accepted by the target model.
    size_t n_gen_tokens = 0; // number of tokens generated by this implementation.
    size_t n_acc_tokens = 0; // number of tokens accepted by the target model.

    std::vector<size_t> n_acc_tokens_per_pos; // number of tokens accepted per draft position.

    // TODO: track performance of most recent calls
    const bool gen_perf = true; // whether to generate performance stats.

    int64_t t_begin_us  = 0; // total time spent in refresh of this implementation in microseconds.
    int64_t t_draft_us  = 0; // total time spent in generating drafts in this implementation in microseconds.
    int64_t t_accept_us = 0; // total time spent in accumulation of this implementation in microseconds.

    common_speculative_impl(common_speculative_type type, uint32_t n_seq, int32_t n_max) : type(type), n_seq(n_seq), n_max(n_max) {}

    virtual ~common_speculative_impl() = default;

    virtual void begin(llama_seq_id seq_id, const llama_tokens & prompt) = 0;

    virtual bool process(const llama_batch & batch) = 0;

    virtual void draft(common_speculative_draft_params_vec & dparams) = 0;

    virtual void accept(llama_seq_id seq_id, uint16_t n_accepted, bool is_other) = 0;

    // the batch process() sees next is the step's last decode, see common_speculative_set_last_decode
    bool last_decode = false;
    // (optional) whether the drafter takes the target's hidden rows of such a decode on the device
    virtual bool leaves_rows() const { return false; }

    // (optional) serialize/restore per-seq internal state (e.g. eagle3's deferred boundary).
    virtual bool get_state(llama_seq_id /*seq_id*/, std::vector<uint8_t> & /*data*/) const { return false; }
    virtual void set_state(llama_seq_id /*seq_id*/, const std::vector<uint8_t> & /*data*/) {}

    // (optional) a draft whose ids are still on the device: the context holding them, and reading them into the
    // draft once the verify that takes them there is queued
    virtual llama_context * ids_pending(llama_seq_id /*seq_id*/) const { return nullptr; }
    virtual bool resolve_ids(llama_seq_id /*seq_id*/) { return false; }
    // (optional) the next decode on ctx_tgt takes those ids for the rows of seq at pos0 + 1 .. pos0 + n, on the device
    virtual bool arm_verify(llama_context * /*ctx_tgt*/, llama_seq_id /*seq_id*/, llama_pos /*pos0*/, int32_t /*n*/) { return false; }
};

// The tokens a drafter's vocabulary counts (llama_draft_note_tokens): a sequence's rows in a batch are a prompt,
// noted whole, or a verify, whose first row is the target's and whose drafts are noted once accepted.
struct common_speculative_draft_notes {
    std::vector<llama_tokens> drafts; // per sequence, the drafts of the last verify batch

    // skip: sequences whose rows the caller notes itself
    void process(llama_context * ctx, const llama_batch & batch, int32_t n_max, const std::vector<bool> * skip = nullptr) {
        for (auto & d : drafts) {
            d.clear();
        }
        for (int32_t k = 0; k < batch.n_tokens; ) {
            const llama_seq_id seq_id = batch.seq_id[k][0];
            int32_t n_rows = 1;
            while (k + n_rows < batch.n_tokens && batch.seq_id[k + n_rows][0] == seq_id) {
                n_rows++;
            }
            if (skip && seq_id >= 0 && (size_t) seq_id < skip->size() && (*skip)[seq_id]) {
                k += n_rows;
                continue;
            }
            if (n_rows > n_max + 1) {
                llama_draft_note_tokens(ctx, seq_id, batch.token + k, n_rows);
            } else if (seq_id >= 0) {
                llama_draft_note_tokens(ctx, seq_id, batch.token + k, 1);
                if (drafts.size() <= (size_t) seq_id) {
                    drafts.resize(seq_id + 1);
                }
                drafts[seq_id].assign(batch.token + k + 1, batch.token + k + n_rows);
            }
            k += n_rows;
        }
    }

    void accept(llama_context * ctx, llama_seq_id seq_id, int32_t n_accepted) {
        if (seq_id < 0 || (size_t) seq_id >= drafts.size()) {
            return;
        }
        auto & d = drafts[seq_id];
        llama_draft_note_tokens(ctx, seq_id, d.data(), std::min<int32_t>(n_accepted, (int32_t) d.size()));
        d.clear();
    }
};

struct common_speculative_impl_draft_simple : public common_speculative_impl {
    common_params_speculative_draft params;

    llama_batch batch;

    std::vector<common_sampler_ptr> smpls;

    common_speculative_draft_notes notes;

    common_speculative_impl_draft_simple(const common_params_speculative & params, uint32_t n_seq)
        : common_speculative_impl(COMMON_SPECULATIVE_TYPE_DRAFT_SIMPLE, n_seq, params.draft.n_max)
        , params(params.draft)
    {
        auto * ctx_dft = this->params.ctx_dft;
        auto * ctx_tgt = this->params.ctx_tgt;

        if (!ctx_dft) {
            throw std::runtime_error("draft-simple requires a draft context");
        }

        SPC_TRC("%s", "adding speculative implementation 'draft-simple'\n");
        SPC_TRC("- n_max=%d, n_min=%d, p_min=%f\n", this->params.n_max, this->params.n_min, this->params.p_min);
        SPC_TRC("- gpu_layers=%d, cache_k=%s, cache_v=%s, ctx_tgt=%s, ctx_dft=%s, devices=[%s]\n",
                this->params.n_gpu_layers,
                (this->params.cache_type_k == GGML_TYPE_COUNT ? "auto" : ggml_type_name(this->params.cache_type_k)),
                (this->params.cache_type_v == GGML_TYPE_COUNT ? "auto" : ggml_type_name(this->params.cache_type_v)),
                ctx_tgt ? "yes" : "no",
                ctx_dft ? "yes" : "no",
                common_speculative_get_devices_str(this->params.devices).c_str());

        batch = llama_batch_init(llama_n_batch(ctx_dft), 0, 1);

        // TODO: optimize or pass from outside?
        // {
        //     common_params_sampling params;
        //     params.no_perf = false;
        //
        //     params.top_k = 40;
        //     params.top_p = 0.9;
        //
        //     params.samplers = {
        //         COMMON_SAMPLER_TYPE_TOP_K,
        //         COMMON_SAMPLER_TYPE_TOP_P,
        //         COMMON_SAMPLER_TYPE_INFILL,
        //     };
        //
        //     result->smpl = common_sampler_init(llama_get_model(ctx_dft), params);
        // }

        smpls.resize(n_seq);
        for (auto & smpl : smpls) {
            common_params_sampling params;
            params.no_perf = false;
            params.top_k = 10;
            params.samplers = {
                COMMON_SAMPLER_TYPE_TOP_K,
            };

            smpl.reset(common_sampler_init(llama_get_model(ctx_dft), params));
        }

        const bool vocab_cmpt = common_speculative_are_compatible(llama_get_model(ctx_tgt), llama_get_model(ctx_dft));
        SPC_DBG("vocab_cmpt = %d\n", vocab_cmpt);

        if (!vocab_cmpt) {
            SPC_ERR("%s", "the target and draft vocabs are not compatible\n");

            throw std::runtime_error("draft model vocab type must match target model to use speculation");
        }

        if (n_seq != llama_n_seq_max(ctx_dft)) {
            SPC_ERR("n_seq mismatch: %d != %d\n", n_seq, llama_n_seq_max(ctx_dft));

            throw std::runtime_error("the draft model number of sequences is incompatible with the speculative n_seq");
        }
    }

    ~common_speculative_impl_draft_simple() override {
        llama_batch_free(batch);
    }

    void begin(llama_seq_id /*seq_id*/, const llama_tokens & /*prompt*/) override {
        // noop
    }

    bool process(const llama_batch & batch) override {
        auto * ctx_dft = params.ctx_dft;

        if (batch.token && batch.seq_id) {
            notes.process(ctx_dft, batch, params.n_max);
        }

        llama_batch batch_dft = batch;
        batch_dft.logits = nullptr;

        const int ret = llama_decode(ctx_dft, batch_dft);

        if (ret != 0) {
            SPC_ERR("failed to decode draft batch, ret = %d\n", ret);

            return false;
        }

        return true;
    }

    void draft(common_speculative_draft_params_vec & dparams) override {
        auto & ctx_dft = params.ctx_dft;

        common_batch_clear(batch);

        // keep track of which sequences are still drafting
        int n_drafting = 0;
        std::vector<bool> drafting(n_seq);

        for (llama_seq_id seq_id = 0; seq_id < (llama_seq_id) n_seq; ++seq_id) {
            auto & dp = dparams[seq_id];

            if (!dp.drafting) {
                continue;
            }

            n_drafting++;
            drafting[seq_id] = true;
            common_sampler_reset(smpls[seq_id].get());

            common_batch_add(batch, dp.id_last, dp.pos0, { seq_id }, true);
        }

        int ret = llama_decode(ctx_dft, batch);
        if (ret != 0) {
            SPC_ERR("llama_decode returned %d\n", ret);
            return;
        }

        int i = 0;

        while (n_drafting > 0) {
            int i_batch = 0;

            common_batch_clear(batch);

            for (llama_seq_id seq_id = 0; seq_id < (llama_seq_id) n_seq; ++seq_id) {
                if (!drafting[seq_id]) {
                    continue;
                }

                auto * smpl = smpls[seq_id].get();

                common_sampler_sample(smpl, ctx_dft, i_batch, true);
                ++i_batch;

                const auto * cur_p = common_sampler_get_candidates(smpl, true);

                for (int k = 0; k < std::min(3, (int) cur_p->size); ++k) {
                    SPC_DBG(" - seq_id %d, draft candidate %3d, pos %3d: %6d (%8.3f) '%s'\n",
                            seq_id, k, i, cur_p->data[k].id, cur_p->data[k].p,
                            common_token_to_piece(ctx_dft, cur_p->data[k].id).c_str());
                }

                // add drafted token for each sequence
                const llama_token id = cur_p->data[0].id;

                // only collect very high-confidence draft tokens
                if (cur_p->data[0].p < params.p_min) {
                    drafting[seq_id] = false;
                    n_drafting--;

                    continue;
                }

                common_sampler_accept(smpl, id, true);

                auto & dp = dparams.at(seq_id);
                auto & result = *dp.result;

                result.push_back(id);

                if ((params.n_max <= (int) result.size()) ||
                    (dp.n_max > 0 && dp.n_max <= (int) result.size())) {
                    drafting[seq_id] = false;
                    n_drafting--;
                    continue;
                }

                common_batch_add(batch, id, dp.pos0 + i + 1, { seq_id }, true);
            }

            if (batch.n_tokens == 0) {
                break;
            }

            // evaluate the drafted tokens on the draft model
            ret = llama_decode(ctx_dft, batch);
            if (ret != 0) {
                SPC_ERR("llama_decode[%d] returned %d\n", i, ret);
                break;
            }

            ++i;
        }

        for (auto & dp : dparams) {
            if (!dp.drafting) {
                continue;
            }

            if (dp.result->size() < (size_t) params.n_min) {
                dp.result->clear();
            }
        }
    }

    void accept(llama_seq_id seq_id, uint16_t n_accepted, bool /*is_other*/) override {
        notes.accept(params.ctx_dft, seq_id, n_accepted);
    }
};


// EAGLE3 speculative decoding state
//
// Input of draft decoder: (This is different compared to MTP)
//   At "pos P", the decoder takes input pair (t_{P+1}, g_P), with RoPE at P.
//     - t_{P+1} = token at sequence pos P+1 (the *next* token after P)
//     - g_P     = encoder output = projection of target's extracted hidden states at P
//
// Deferred boundary (MTP doesn't have this issue):
//   Within a single process() call with n_tokens, we can only write decoder KV for
//   training pos 0..n_tokens-2. The last training pos (n_tokens-1) needs t_{n_tokens}
//   which lies *outside* this batch — it is the token target will sample next or the first token from next ubatch.
//   So the last training pos of each process() call is *deferred* to whichever next call has
//   the missing token in hand:
//     - multi-ubatch prefill: the next process()'s first token completes the pair
//                              (handled by the per-seq "cross-ubatch bridge")
//     - single-ubatch prefill / after verify: draft()'s seed step uses "dp.id_last"
//                              (target's freshest sample) to complete the pair
//
// Per-seq carry-over state:
//   pending_g_last    [n_embd_dec]  ┐  the deferred boundary's (g, pos). Set by
//   pending_pos_last  llama_pos     ┘  process() at end of ubatch (= last row);
//                                       rebased by accept() to first-non-accepted pos.
//   verify_g          [N × n_embd_dec] snapshot of process()'s encoder output;
//   verify_pos_first  llama_pos         consumed by accept() to recover the right
//   verify_g_rows     int32_t           pending_g_last row for any n_accepted value.
//
// Performance is overall good but there is waste in verify cycle:
//   process() runs encoder + decoder on the *full* verify batch including rows for
//   rejected drafts. The KV at those positions is then dropped.
//
// TODO: Not sure if we need optimization for this waste?
// If so we may need hybrid stash:
//      in verify mode, have process() only stash features and let draft() seed run
//      encoder+decoder on n_accepted+1 rows).
struct common_speculative_impl_draft_eagle3 : public common_speculative_impl {
    common_params_speculative_draft params;
    llama_batch batch;

    std::vector<common_sampler_ptr> smpls;

    // backend sampler chain per seq, attached to ctx_dft
    std::vector<llama_sampler *> backend_chains;

    int32_t n_embd_dec = 0;       // draft hidden size
    int32_t n_embd_enc = 0;       // target_layer_ids_n * target_hidden_size
    int32_t n_embd_tgt = 0;       // target model hidden size
    int32_t n_layer_tgt = 0;      // target model layer count

    const int32_t * target_layer_ids   = nullptr; // model_dft's extract layer indices
    uint32_t        target_layer_ids_n = 0;

    // [per-seq] deferred boundary state
    std::vector<std::vector<float>> pending_g_last;
    std::vector<llama_pos>          pending_pos_last;

    // [per-seq] snapshot of the most recent process()'s encoder output
    std::vector<std::vector<float>> verify_g;         // [n_seq][n_rows * n_embd_dec]
    std::vector<llama_pos>          verify_pos_first; // [n_seq] — pos of verify_g[seq][0]
    std::vector<int32_t>            verify_g_rows;    // [n_seq] — number of rows

    // scratch buffer for concatenated target features [n_tokens, n_embd_enc]
    std::vector<float> features_buf;
    std::vector<float> g_embd_buf;

    common_speculative_impl_draft_eagle3(const common_params_speculative & params, uint32_t n_seq)
        : common_speculative_impl(COMMON_SPECULATIVE_TYPE_DRAFT_EAGLE3, n_seq, params.draft.n_max)
        , params(params.draft)
    {
        SPC_TRC("%s", "adding speculative implementation 'draft-eagle3'\n");
        SPC_TRC("- n_max=%d, n_min=%d, p_min=%f, backend_sampling=%d\n", params.draft.n_max, params.draft.n_min, params.draft.p_min, (int) params.draft.backend_sampling);

        auto * ctx_tgt = this->params.ctx_tgt;
        auto * ctx_dft = this->params.ctx_dft;
        GGML_ASSERT(ctx_tgt && ctx_dft && "EAGLE3 requires ctx_tgt and ctx_dft to be set");

        const llama_model * model_dft = llama_get_model(ctx_dft);
        const llama_model * model_tgt = llama_get_model(ctx_tgt);

        target_layer_ids   = llama_model_target_layer_ids  (model_dft);
        target_layer_ids_n = llama_model_target_layer_ids_n(model_dft);
        if (target_layer_ids_n != 3) {
            throw std::runtime_error("draft model is not eagle3 (expected 3 extract layers, got " +
                                     std::to_string(target_layer_ids_n) + ")");
        }

        n_embd_tgt = llama_model_n_embd(model_tgt);
        n_embd_dec = llama_model_n_embd(model_dft);
        n_embd_enc = (int32_t) target_layer_ids_n * n_embd_tgt;
        n_layer_tgt = llama_model_n_layer(model_tgt);

        const int32_t n_b = (int32_t) llama_n_batch(ctx_dft);
        batch = llama_batch_init(/*n_tokens=*/ n_b, /*embd=*/ n_embd_dec, /*n_seq_max=*/ 1);
        // llama_batch_init allocates only one of token/embd; eagle3 decoder needs both.
        // TODO: fix, how to call without malloc
        batch.token = (llama_token *) malloc(sizeof(llama_token) * n_b);

        smpls.resize(n_seq);
        for (auto & s : smpls) {
            common_params_sampling sparams;
            sparams.no_perf  = false;
            sparams.top_k    = 10;
            sparams.samplers = { COMMON_SAMPLER_TYPE_TOP_K };
            s.reset(common_sampler_init(llama_get_model(ctx_dft), sparams));
        }

        // offload draft sampling to the backend
        backend_chains.assign(n_seq, nullptr);
        if (this->params.backend_sampling) {
            for (llama_seq_id seq_id = 0; seq_id < (llama_seq_id) n_seq; ++seq_id) {
                llama_sampler * chain = llama_sampler_chain_init(llama_sampler_chain_default_params());
                llama_sampler_chain_add(chain, llama_sampler_init_top_k(10));

                if (!llama_set_sampler(ctx_dft, seq_id, chain)) {
                    SPC_WRN("backend offload failed for seq_id=%d; using CPU sampler\n", (int) seq_id);
                    llama_sampler_free(chain);
                    chain = nullptr;
                }
                backend_chains[seq_id] = chain;
            }
        }

        // turn on extraction of the target layers' hidden states
        for (uint32_t k = 0; k < target_layer_ids_n; ++k) {
            if (target_layer_ids[k] < n_layer_tgt) {
                llama_set_embeddings_layer_inp(ctx_tgt, (uint32_t) target_layer_ids[k], true);
            } else if (target_layer_ids[k] == n_layer_tgt) {
                llama_set_embeddings_nextn(ctx_tgt, true, /*masked*/ false);
            } else {
                GGML_ABORT("EAGLE3: target layer id %d exceeds target n_layer %d", target_layer_ids[k], n_layer_tgt);
            }
        }

        // turn on extraction of the draft model's pre-norm hidden state
        // (used both for the encoder output g_embd and the decoder pre-norm output).
        llama_set_embeddings_nextn(ctx_dft, true, /*masked*/ true);

        pending_g_last.assign(n_seq, std::vector<float>(n_embd_dec, 0.0f));
        pending_pos_last.assign(n_seq, -1);

        verify_g.assign(n_seq, std::vector<float>());
        verify_pos_first.assign(n_seq, -1);
        verify_g_rows.assign(n_seq, 0);
    }

    ~common_speculative_impl_draft_eagle3() override {
        auto * ctx_dft = this->params.ctx_dft;
        for (llama_seq_id seq_id = 0; seq_id < (llama_seq_id) backend_chains.size(); ++seq_id) {
            if (backend_chains[seq_id] == nullptr) {
                continue;
            }
            if (ctx_dft) {
                llama_set_sampler(ctx_dft, seq_id, nullptr);
            }
            llama_sampler_free(backend_chains[seq_id]);
        }
        backend_chains.clear();

        if (batch.token != nullptr) {
            free(batch.token);
            batch.token = nullptr;
        }
        llama_batch_free(batch);
    }

    void begin(llama_seq_id seq_id, const llama_tokens & prompt) override {
        const int32_t N = (int32_t) prompt.size();
        if (N <= 0) {
            return;
        }
        // expected state after prefill: ctx_dft has pos 0..N-2 (last position is deferred to
        // draft()'s seed step). Warn only if more than one position is missing.
        auto * ctx_dft = this->params.ctx_dft;
        const llama_pos pos_max = llama_memory_seq_pos_max(llama_get_memory(ctx_dft), seq_id);
        if (pos_max < N - 2) {
            SPC_WRN("ctx_dft pos_max=%d < N-2=%d — process() did not run on every prefill ubatch. "
                    "Drafts may degrade.\n",
                    (int) pos_max, N - 2);
        }
    }

    bool process(const llama_batch & batch_in) override {
        if (batch_in.n_tokens <= 0) {
            return true;
        }

        if (batch_in.token == nullptr || batch_in.embd != nullptr) {
            return true;
        }

        const int32_t n_tokens = batch_in.n_tokens;

        // i_batch_beg[seq] / i_batch_end[seq]: inclusive batch indices of this seq's
        // first/last token in batch_in. Assumes per-seq tokens are contiguous within
        // the ubatch (server's default ordering).
        std::vector<int32_t> i_batch_beg(n_seq, -1);
        std::vector<int32_t> i_batch_end(n_seq, -1);
        for (int k = 0; k < n_tokens; ++k) {
            GGML_ASSERT(batch_in.n_seq_id[k] == 1);
            const llama_seq_id seq_id = batch_in.seq_id[k][0];
            if (seq_id < 0 || seq_id >= (llama_seq_id) n_seq) {
                continue;
            }
            i_batch_end[seq_id] = k;
            if (i_batch_beg[seq_id] < 0) {
                i_batch_beg[seq_id] = k;
            }
        }

        auto * ctx_tgt = this->params.ctx_tgt;
        auto * ctx_dft = this->params.ctx_dft;

        // Interleave each extract_layer's hidden state into a contiguous buffer of
        // shape [n_tokens, target_layer_ids_n * n_embd_tgt]. Then run EAGLE3 encoder
        // to get one g_embd row per token.
        features_buf.resize((size_t) n_tokens * n_embd_enc, 0.0f);

        for (uint32_t k = 0; k < target_layer_ids_n; ++k) {
            const float * layer = target_layer_ids[k] < n_layer_tgt
                ? llama_get_embeddings_layer_inp(ctx_tgt, (uint32_t) target_layer_ids[k])
                : llama_get_embeddings_nextn(ctx_tgt);
            if (!layer) {
                GGML_ABORT("EAGLE3: target layer %d input not extracted.", target_layer_ids[k]);
            }
            for (int32_t i = 0; i < n_tokens; ++i) {
                float * dst = features_buf.data() + (size_t) i * n_embd_enc + k * (size_t) n_embd_tgt;
                const float * src = layer + (size_t) i * n_embd_tgt;
                std::memcpy(dst, src, (size_t) n_embd_tgt * sizeof(float));
            }
        }

        g_embd_buf.resize((size_t) n_tokens * n_embd_dec);

        // llama_encode() requires the full encoder batch to fit in n_ubatch.
        // Allow batch > ubatch: eagle3's per-token encoder can be chunked safely.
        const int32_t n_ubatch_dft = (int32_t) llama_n_ubatch(ctx_dft);
        for (int32_t i = 0; i < n_tokens; i += n_ubatch_dft) {
            const int32_t n_chunk = std::min(n_ubatch_dft, n_tokens - i);

            llama_batch enc_batch = {
                /*.n_tokens =*/ n_chunk,
                /*.token    =*/ nullptr,
                /*.embd     =*/ features_buf.data() + (size_t) i * n_embd_enc,
                /*.pos      =*/ nullptr,
                /*.n_seq_id =*/ nullptr,
                /*.seq_id   =*/ nullptr,
                /*.logits   =*/ nullptr,
            };
            const int32_t rc = llama_encode(ctx_dft, enc_batch);
            if (rc != 0) {
                SPC_ERR("llama_encode(ctx_dft) failed rc=%d (n_tokens=%d, offset=%d)\n",
                        rc, (int) n_chunk, (int) i);
                return false;
            }

            // g_embd has shape [n_chunk, n_embd_dec] in ctx_dft's pre-norm embeddings buffer.
            const float * g_embd_chunk = llama_get_embeddings_nextn(ctx_dft);
            GGML_ASSERT(g_embd_chunk && "EAGLE3 encoder produced no output.");
            std::memcpy(g_embd_buf.data() + (size_t) i * n_embd_dec,
                        g_embd_chunk,
                        (size_t) n_chunk * n_embd_dec * sizeof(float));
        }

        const float * g_embd = g_embd_buf.data();

        const size_t row_bytes = (size_t) n_embd_dec * sizeof(float);

        // EAGLE3 decoder input convention: at memory pos P the input pair is
        // (token[P+1], g_embd[P]). This shifts the token index "left by one" relative to g_embd.
        //
        // Per seq, in order:
        //   (a) cross-ubatch bridge — when applicable, write the previously-deferred
        //       pos using this ubatch's first token + pending_g_last.
        //   (b) main write loop — for k in [beg, end-1], write (token[k+1], g_embd[k])
        //       at pos[k]. The last training pos (k=end) is left unwritten = new
        //       deferred boundary, completed by the next process() or draft() call.
        //   (c) refresh deferred state — stash this ubatch's full g_embd into verify_g,
        //       update pending_g_last / pending_pos_last to the last row.
        common_batch_clear(batch);

        for (llama_seq_id seq_id = 0; seq_id < (llama_seq_id) n_seq; ++seq_id) {
            const int32_t beg = i_batch_beg[seq_id];
            const int32_t end = i_batch_end[seq_id];
            if (beg < 0 || end < 0) {
                continue;
            }

            // cross-ubatch bridge — complete the prior ubatch's deferred boundary.
            // Fires iff all three preconditions hold:
            //   1) pending_pos_last >= 0
            //   2) pending_pos_last + 1 == pos[beg]
            //   3) pending_pos_last > dft_pos_max // TODO: is this check needed?
            const llama_pos pending_pos = pending_pos_last[seq_id];
            if (pending_pos >= 0 && pending_pos + 1 == batch_in.pos[beg]) {
                const llama_pos dft_pos_max = llama_memory_seq_pos_max(llama_get_memory(ctx_dft), seq_id);
                if (pending_pos > dft_pos_max) {
                    common_batch_add(batch, batch_in.token[beg], pending_pos, { seq_id }, /*logits=*/ false);
                    std::memcpy(batch.embd + (size_t) (batch.n_tokens - 1) * n_embd_dec,
                                pending_g_last[seq_id].data(), row_bytes);
                }
            }

            for (int32_t k = beg; k < end; ++k) {
                common_batch_add(batch, batch_in.token[k + 1], batch_in.pos[k], { seq_id }, /*logits=*/ false);
                std::memcpy(batch.embd + (size_t) (batch.n_tokens - 1) * n_embd_dec,
                            g_embd + (size_t) k * n_embd_dec, row_bytes);
            }

            // refresh deferred state
            const int32_t n_rows = end - beg + 1;
            verify_pos_first[seq_id] = batch_in.pos[beg];
            pending_pos_last[seq_id] = batch_in.pos[end];
            verify_g_rows[seq_id]    = n_rows;
            verify_g[seq_id].resize((size_t) n_rows * n_embd_dec, 0.0f);
            std::memcpy(verify_g[seq_id].data(),       g_embd + (size_t) beg * n_embd_dec, row_bytes * n_rows);
            std::memcpy(pending_g_last[seq_id].data(), g_embd + (size_t) end * n_embd_dec, row_bytes);
        }

        if (batch.n_tokens > 0) {
            const int32_t rc = llama_decode(ctx_dft, batch);
            if (rc != 0) {
                SPC_ERR("llama_decode(ctx_dft) failed rc=%d (n_tokens=%d, ubatch_pos[0]=%d)\n",
                        rc, (int) batch.n_tokens, (int) batch_in.pos[0]);
                return false;
            }
        }

        return true;
    }

    void draft(common_speculative_draft_params_vec & dparams) override {
        auto & ctx_dft = params.ctx_dft;

        common_batch_clear(batch);

        // keep track of which sequences are still drafting
        int n_drafting = 0;
        std::vector<bool> drafting(n_seq);

        const size_t row_bytes = (size_t) n_embd_dec * sizeof(float);

        // Complete the deferred boundary pair (dp.id_last, pending_g_last) at memory
        // pos pending_pos_last. dp.id_last is target's freshest sample (= corrected
        // token after verify, or first generated token after prefill), matching the
        // EAGLE3 input convention (token[P+1], g_embd[P]) at pos P.
        for (llama_seq_id seq_id = 0; seq_id < (llama_seq_id) n_seq; ++seq_id) {
            auto & dp = dparams[seq_id];

            if (!dp.drafting) {
                continue;
            }
            if (pending_pos_last[seq_id] < 0) {
                continue;
            }

            n_drafting++;
            drafting[seq_id] = true;
            common_sampler_reset(smpls[seq_id].get());

            llama_memory_seq_rm(llama_get_memory(ctx_dft), seq_id, pending_pos_last[seq_id], -1);

            common_batch_add(batch, dp.id_last, pending_pos_last[seq_id], { seq_id }, true);
            std::memcpy(batch.embd + (size_t) (batch.n_tokens - 1) * n_embd_dec,
                        pending_g_last[seq_id].data(),
                        row_bytes);
        }

        if (batch.n_tokens == 0) {
            return;
        }

        int ret = llama_decode(ctx_dft, batch);
        if (ret != 0) {
            SPC_ERR("llama_decode returned %d\n", ret);
            return;
        }

        int i = 0;

        while (n_drafting > 0) {
            int i_batch = 0;

            common_batch_clear(batch);

            for (llama_seq_id seq_id = 0; seq_id < (llama_seq_id) n_seq; ++seq_id) {
                if (!drafting[seq_id]) {
                    continue;
                }

                auto * smpl = smpls[seq_id].get();

                common_sampler_sample(smpl, ctx_dft, i_batch, true);
                // pre-norm hidden state of this position becomes g_embd for the next step
                const float * prenorm = llama_get_embeddings_nextn_ith(ctx_dft, i_batch);
                ++i_batch;

                const auto * cur_p = common_sampler_get_candidates(smpl, true);

                for (int k = 0; k < std::min(3, (int) cur_p->size); ++k) {
                    SPC_DBG(" - seq_id %d, draft candidate %3d, pos %3d: %6d (%8.3f) '%s'\n",
                            seq_id, k, i, cur_p->data[k].id, cur_p->data[k].p,
                            common_token_to_piece(ctx_dft, cur_p->data[k].id).c_str());
                }

                const llama_token id = cur_p->data[0].id;

                // only collect very high-confidence draft tokens
                // (configurable via --spec-draft-p-min, set to 0.0 to disable early-stop)
                if (cur_p->data[0].p < params.p_min) {
                    drafting[seq_id] = false;
                    n_drafting--;

                    continue;
                }

                common_sampler_accept(smpl, id, true);

                auto & dp = dparams.at(seq_id);
                auto & result = *dp.result;

                result.push_back(id);

                if (params.n_max <= (int) result.size()) {
                    drafting[seq_id] = false;
                    n_drafting--;
                    continue;
                }

                common_batch_add(batch, id, pending_pos_last[seq_id] + (i + 1), { seq_id }, true);
                std::memcpy(batch.embd + (size_t) (batch.n_tokens - 1) * n_embd_dec, prenorm, row_bytes);
            }

            if (batch.n_tokens == 0) {
                break;
            }

            ret = llama_decode(ctx_dft, batch);
            if (ret != 0) {
                SPC_ERR("llama_decode[%d] returned %d\n", i, ret);
                break;
            }

            ++i;
        }

        for (llama_seq_id seq_id = 0; seq_id < (llama_seq_id) n_seq; ++seq_id) {
            auto & dp = dparams[seq_id];
            if (!dp.drafting) {
                continue;
            }

            if (dp.result->size() < (size_t) params.n_min) {
                dp.result->clear();
            }
        }
    }

    void accept(llama_seq_id seq_id, uint16_t n_accepted, bool /*is_other*/) override {
        if (seq_id < 0 || seq_id >= (llama_seq_id) n_seq) {
            return;
        }

        const int32_t n_rows = verify_g_rows[seq_id];
        if (n_rows <= 0) {
            return;
        }

        const int32_t i_g = std::min<int32_t>(n_accepted, n_rows - 1);
        pending_pos_last[seq_id] = verify_pos_first[seq_id] + i_g;
        std::memcpy(pending_g_last[seq_id].data(),
                    verify_g[seq_id].data() + (size_t) i_g * n_embd_dec,
                    (size_t) n_embd_dec * sizeof(float));
    }

    // we only need to stash the deferred boundary's g_embd row for recurrent/hybrid targets:
    // their single-position checkpoints drop it on restore
    bool need_boundary_stash() const {
        const llama_model * model_tgt = llama_get_model(params.ctx_tgt);
        return llama_model_is_recurrent(model_tgt) || llama_model_is_hybrid(model_tgt);
    }

    bool get_state(llama_seq_id seq_id, std::vector<uint8_t> & data) const override {
        if (!need_boundary_stash()) {
            return false;
        }
        if (seq_id < 0 || seq_id >= (llama_seq_id) n_seq || pending_pos_last[seq_id] < 0) {
            return false;
        }

        const llama_pos          pos = pending_pos_last[seq_id];
        const std::vector<float> & g = pending_g_last[seq_id];

        data.resize(sizeof(llama_pos) + g.size() * sizeof(float));
        std::memcpy(data.data(),                     &pos,     sizeof(llama_pos));
        std::memcpy(data.data() + sizeof(llama_pos), g.data(), g.size() * sizeof(float));
        return true;
    }

    void set_state(llama_seq_id seq_id, const std::vector<uint8_t> & data) override {
        if (!need_boundary_stash()) {
            return;
        }
        if (seq_id < 0 || seq_id >= (llama_seq_id) n_seq) {
            return;
        }
        if (data.size() != sizeof(llama_pos) + (size_t) n_embd_dec * sizeof(float)) {
            return;
        }

        llama_pos pos = -1;
        std::memcpy(&pos, data.data(), sizeof(llama_pos));

        pending_pos_last[seq_id] = pos;
        pending_g_last[seq_id].resize(n_embd_dec);
        std::memcpy(pending_g_last[seq_id].data(), data.data() + sizeof(llama_pos), (size_t) n_embd_dec * sizeof(float));
    }
};

// DFlash: block-diffusion drafting with a draft-side KV cache injection
struct common_speculative_impl_draft_dflash : public common_speculative_impl {
    common_params_speculative_draft params;

    llama_batch batch;        // noise tokens
    llama_batch batch_inject; // target features for KV cache injection

    std::vector<common_sampler_ptr> smpls;

    // backend sampler chain per seq, attached to ctx_dft
    std::vector<llama_sampler *> backend_chains;

    int32_t n_embd_dec = 0;  // draft hidden size
    int32_t n_embd_enc = 0;  // target_layer_ids_n * target_hidden_size
    int32_t n_embd_tgt = 0;  // target model hidden size

    int32_t     block_size    = 0;
    llama_token mask_token_id = 0;

    bool    is_dflash2     = false;
    bool    is_mrope       = false;
    int32_t selector_top_k = 0;

    // draft-dspark: the draft carries a Markov head and uses an anchor-first block layout
    const bool is_dspark;

    // dspark speculators
    bool sample_from_anchor = true;

    // block-internal attention
    bool causal_attn = false;

    const int32_t * target_layer_ids   = nullptr; // model_dft's extract layer indices
    uint32_t        target_layer_ids_n = 0;

    common_speculative_impl_draft_dflash(const common_params_speculative & params, uint32_t n_seq,
            common_speculative_type type = COMMON_SPECULATIVE_TYPE_DRAFT_DFLASH)
        : common_speculative_impl(type, n_seq, params.draft.n_max)
        , params(params.draft)
        , is_dspark(type == COMMON_SPECULATIVE_TYPE_DRAFT_DSPARK)
    {
        auto * ctx_tgt = this->params.ctx_tgt;
        auto * ctx_dft = this->params.ctx_dft;
        GGML_ASSERT(ctx_tgt && ctx_dft && "DFlash requires ctx_tgt and ctx_dft to be set");

        const llama_model * model_dft = llama_get_model(ctx_dft);
        const llama_model * model_tgt = llama_get_model(ctx_tgt);

        target_layer_ids   = llama_model_target_layer_ids  (model_dft);
        target_layer_ids_n = llama_model_target_layer_ids_n(model_dft);
        GGML_ASSERT(target_layer_ids_n > 0 && "DFlash model has no target_layer_ids");

        n_embd_tgt    = llama_model_n_embd(model_tgt);
        n_embd_dec    = llama_model_n_embd(model_dft);
        n_embd_enc    = (int32_t) target_layer_ids_n * n_embd_tgt;

        // read the trained block size from the dflash.block_size metadata key
        block_size = 16;
        {
            char buf[32] = {};
            if (llama_model_meta_val_str(model_dft, "dflash.block_size", buf, sizeof(buf)) >= 0) {
                block_size = std::atoi(buf);
            }
            if (llama_model_meta_val_str(model_dft, "dflash.sample_from_anchor", buf, sizeof(buf)) >= 0) {
                sample_from_anchor = std::strcmp(buf, "true") == 0;
            }
            if (llama_model_meta_val_str(model_dft, "dflash.attention.causal", buf, sizeof(buf)) >= 0) {
                causal_attn = std::strcmp(buf, "true") == 0;
            }
        }

        selector_top_k = llama_model_dflash_selector_top_k(model_dft);
        is_dflash2     = selector_top_k > 0;
        mask_token_id = llama_vocab_mask(llama_model_get_vocab(model_dft));

        if (is_dspark && this->params.p_min > 0.0f) {
            char buf[16] = {};
            const bool has_conf =
                llama_model_meta_val_str(model_dft, "dflash.has_confidence_head", buf, sizeof(buf)) < 0 ||
                std::strcmp(buf, "true") == 0;
            if (!has_conf) {
                throw std::runtime_error("DSpark draft has no confidence head: please set --spec-draft-p-min 0");
            }
        }

        LOG_INF("%s: adding speculative implementation '%s'\n", __func__, common_speculative_type_to_str(type).c_str());
        LOG_INF("%s: - n_max=%d, n_min=%d, p_min=%.2f\n", __func__, this->params.n_max, this->params.n_min, this->params.p_min);
        LOG_INF("%s: - block_size=%d, mask_token_id=%d, n_extract=%u, sample_from_anchor=%s\n", __func__,
                block_size, mask_token_id, target_layer_ids_n, sample_from_anchor ? "true" : "false");

        // DFlash input is [id_last, <mask> * (block_size-1)]: in-place denoising yields at most
        // block_size-1 draft tokens, anchor-first DSpark yields a full block_size draft tokens
        const int32_t n_draft_max = is_dspark && sample_from_anchor ? block_size : block_size - 1;
        if (this->params.n_max > n_draft_max || this->params.n_min > n_draft_max) {
            LOG_WRN("%s: requested draft size (n_max=%d, n_min=%d) exceeds the trained block size %d -- clamping to %d\n",
                    __func__, this->params.n_max, this->params.n_min, block_size, n_draft_max);
            this->params.n_max = std::min(this->params.n_max, n_draft_max);
            this->params.n_min = std::min(this->params.n_min, n_draft_max);
        }
        this->n_max = this->params.n_max;

        batch        = llama_batch_init(llama_n_batch(ctx_dft), 0,          n_seq);
        batch_inject = llama_batch_init(llama_n_ubatch(ctx_dft), n_embd_enc, n_seq);

        // embd batches on an M-RoPE draft need 4 position rows per token
        is_mrope = llama_model_rope_type(model_dft) == LLAMA_ROPE_TYPE_MROPE;
        if (is_mrope) {
            free(batch_inject.pos);
            batch_inject.pos = (llama_pos *) malloc(sizeof(llama_pos) * 4 * llama_n_batch(ctx_dft));
        }

        smpls.resize(n_seq);
        for (auto & s : smpls) {
            common_params_sampling sparams;
            sparams.no_perf  = false;
            sparams.top_k    = 10;
            sparams.samplers = { COMMON_SAMPLER_TYPE_TOP_K };
            s.reset(common_sampler_init(model_dft, sparams));
        }

        // offload draft sampling to the backend
        backend_chains.assign(n_seq, nullptr);
        if (this->params.backend_sampling && !is_dflash2) {
            for (llama_seq_id seq_id = 0; seq_id < (llama_seq_id) n_seq; ++seq_id) {
                llama_sampler * chain = llama_sampler_chain_init(llama_sampler_chain_default_params());
                llama_sampler_chain_add(chain, llama_sampler_init_top_k(10));

                if (!llama_set_sampler(ctx_dft, seq_id, chain)) {
                    SPC_WRN("backend offload failed for seq_id=%d; using CPU sampler\n", (int) seq_id);
                    llama_sampler_free(chain);
                    chain = nullptr;
                }
                backend_chains[seq_id] = chain;
            }
        }

        // turn on extraction of the target layers' input embeddings
        for (uint32_t k = 0; k < target_layer_ids_n; ++k) {
            llama_set_embeddings_layer_inp(ctx_tgt, (uint32_t) target_layer_ids[k], true);
        }

        // DFlash2 reads its selector lattice from h_nextn and never consumes raw logits.
        llama_set_embeddings_nextn(ctx_dft, true, /*masked*/ !is_dflash2);
        llama_set_causal_attn(ctx_dft, causal_attn); // DFlash needs non-causal attention unless the model says otherwise
    }

    ~common_speculative_impl_draft_dflash() override {
        auto * ctx_dft = this->params.ctx_dft;
        for (llama_seq_id seq_id = 0; seq_id < (llama_seq_id) backend_chains.size(); ++seq_id) {
            if (backend_chains[seq_id] == nullptr) {
                continue;
            }
            if (ctx_dft) {
                llama_set_sampler(ctx_dft, seq_id, nullptr);
            }
            llama_sampler_free(backend_chains[seq_id]);
        }
        backend_chains.clear();

        llama_batch_free(batch);
        llama_batch_free(batch_inject);
    }

    void begin(llama_seq_id seq_id, const llama_tokens & prompt) override {
        if (seq_id < 0 || seq_id >= (llama_seq_id) n_seq) {
            return;
        }

        const int32_t N = (int32_t) prompt.size();
        if (N <= 0) {
            return;
        }

        const llama_pos pos_max = llama_memory_seq_pos_max(llama_get_memory(params.ctx_dft), seq_id);
        if (pos_max < N - 1) {
            LOG_WRN("%s: ctx_dft pos_max=%d < N-1=%d - process() did not run on every prefill ubatch. "
                    "Drafts may degrade.\n",
                    __func__, (int) pos_max, N - 1);
        }
    }

    bool process(const llama_batch & batch_in) override {
        if (batch_in.n_tokens <= 0) {
            return true;
        }

        // Target prefill may contain token IDs or multimodal embeddings. Both
        // produce the target-layer features used to seed the draft KV cache, so
        // embeddings are injected too, except the pinned ones skipped below.
        // TODO: revisit after https://github.com/ggml-org/llama.cpp/pull/24669 is merged
        const bool has_tokens     = batch_in.token != nullptr;
        const bool has_embeddings = batch_in.embd  != nullptr;
        if (has_tokens == has_embeddings) {
            return true;
        }

        const int32_t n_tokens = batch_in.n_tokens;

        // per-seq inclusive batch range (assumes each seq's tokens are contiguous in the batch)
        std::vector<int32_t> i_batch_beg(n_seq, -1);
        std::vector<int32_t> i_batch_end(n_seq, -1);
        for (int32_t k = 0; k < n_tokens; ++k) {
            GGML_ASSERT(batch_in.n_seq_id[k] == 1);
            const llama_seq_id seq_id = batch_in.seq_id[k][0];
            if (seq_id < 0 || seq_id >= (llama_seq_id) n_seq) {
                continue;
            }
            i_batch_end[seq_id] = k;
            if (i_batch_beg[seq_id] < 0) {
                i_batch_beg[seq_id] = k;
            }
        }

        auto * ctx_tgt = this->params.ctx_tgt;
        auto * ctx_dft = this->params.ctx_dft;

        const int32_t n_ubatch = (int32_t) llama_n_ubatch(ctx_dft);

        for (llama_seq_id seq_id = 0; seq_id < (llama_seq_id) n_seq; ++seq_id) {
            if (i_batch_beg[seq_id] < 0) {
                continue;
            }
            const int32_t n_rows = i_batch_end[seq_id] - i_batch_beg[seq_id] + 1;

            // an M-RoPE image pins all its rows to one position, so a windowed draft
            // cache cannot free cells for it - skip it, the draft can jump over the gap
            const bool pos_pinned = batch_in.pos[i_batch_beg[seq_id]] == batch_in.pos[i_batch_end[seq_id]];
            if (has_embeddings && n_rows > 1 && pos_pinned) {
                continue;
            }

            for (int32_t offset = 0; offset < n_rows; offset += n_ubatch) {
                const int32_t n_chunk = std::min(n_ubatch, n_rows - offset);

                // gather target features per extract layer; the fused decode encodes and
                // injects them into the K/V cache at the target positions
                batch_inject.n_tokens = n_chunk;
                for (uint32_t k = 0; k < target_layer_ids_n; ++k) {
                    const float * layer = llama_get_embeddings_layer_inp(ctx_tgt, (uint32_t) target_layer_ids[k]);
                    if (!layer) {
                        GGML_ABORT("DFlash: target layer %d input not extracted.", target_layer_ids[k]);
                    }
                    for (int32_t i = 0; i < n_chunk; ++i) {
                        float       * dst = batch_inject.embd + (size_t) i * n_embd_enc + k * (size_t) n_embd_tgt;
                        const float * src = layer + (size_t) (i_batch_beg[seq_id] + offset + i) * n_embd_tgt;
                        std::memcpy(dst, src, (size_t) n_embd_tgt * sizeof(float));
                    }
                }

                for (int32_t i = 0; i < n_chunk; ++i) {
                    const llama_pos p = batch_in.pos[i_batch_beg[seq_id] + offset + i];
                    batch_inject.pos[i] = p;
                    if (is_mrope) {
                        batch_inject.pos[1 * n_chunk + i] = p;
                        batch_inject.pos[2 * n_chunk + i] = p;
                        batch_inject.pos[3 * n_chunk + i] = 0;
                    }
                    batch_inject.n_seq_id[i]  = 1;
                    batch_inject.seq_id[i][0] = seq_id;
                    batch_inject.logits[i]    = false;
                }
                const int32_t rc = llama_decode(ctx_dft, batch_inject);
                if (rc != 0) {
                    LOG_ERR("%s: llama_decode(ctx_dft) failed rc=%d (n_tokens=%d, offset=%d)\n",
                            __func__, rc, (int) n_chunk, (int) offset);
                    return false;
                }
            }
        }

        return true;
    }

    void draft(common_speculative_draft_params_vec & dparams) override {
        auto & ctx_dft = params.ctx_dft;

        common_batch_clear(batch);

        // build one batch holding every drafting sequence's noise block into a single decode)
        // record where each block starts and its size
        std::vector<int32_t> i_block_beg(n_seq, -1);
        std::vector<int32_t> n_block    (n_seq,  0);

        for (llama_seq_id seq_id = 0; seq_id < (llama_seq_id) n_seq; ++seq_id) {
            auto & dp = dparams[seq_id];
            if (!dp.drafting) {
                continue;
            }

            common_sampler_reset(smpls[seq_id].get());

            const int32_t n = (int32_t) dp.pos0;

            const int32_t n_draft = params.n_max;

            const int32_t n_block_tokens = n_draft + (is_dspark && sample_from_anchor ? 0 : 1);
            i_block_beg[seq_id] = batch.n_tokens;
            n_block    [seq_id] = n_block_tokens;
            for (int32_t i = 0; i < n_block_tokens; ++i) {
                common_batch_add(batch, i == 0 ? dp.id_last : mask_token_id, n + i, { seq_id }, !is_dflash2);
            }
        }

        if (batch.n_tokens == 0) {
            return;
        }

        // decode all sequence's noise block in a single batch
        int ret = llama_decode(ctx_dft, batch);
        if (ret != 0) {
            LOG_WRN("%s: llama_decode returned %d\n", __func__, ret);
            return;
        }

        for (llama_seq_id seq_id = 0; seq_id < (llama_seq_id) n_seq; ++seq_id) {
            if (i_block_beg[seq_id] < 0) {
                continue;
            }
            auto & dp = dparams[seq_id];

            const int32_t beg            = i_block_beg[seq_id];
            const int32_t n_block_tokens = n_block[seq_id];

            auto * smpl = smpls[seq_id].get();

            auto & result = *dp.result;

            if (is_dflash2) {
                const float * lattice = llama_get_embeddings_nextn(ctx_dft);
                GGML_ASSERT(lattice && "DFlash2 selector produced no lattice");

                int32_t predecessor = 0;
                for (int32_t i = 1; i < n_block_tokens; ++i) {
                    const float * row = lattice + (size_t) (beg + i) * n_embd_dec;
                    const float * scores = row + selector_top_k + (size_t) predecessor * selector_top_k;

                    predecessor = (int32_t) std::distance(scores,
                            std::max_element(scores, scores + selector_top_k));
                    if (params.p_min > 0.0f) {
                        // softmax(scores) at the argmax, i.e. 1 / sum(exp(s_k - s_max))
                        float sum = 0.0f;
                        for (int32_t k = 0; k < selector_top_k; ++k) {
                            sum += std::exp(scores[k] - scores[predecessor]);
                        }
                        if (1.0f / sum < params.p_min) {
                            break;
                        }
                    }
                    result.push_back((llama_token) row[predecessor]);
                }

                if (result.size() < (size_t) params.n_min) {
                    result.clear();
                }
                continue;
            }

            if (is_dspark) {
                // DSpark: read from the first draft slot, truncate below the confidence threshold
                const float * conf = params.p_min > 0.0f ? llama_get_embeddings_nextn(ctx_dft) : nullptr;
                // bonus-anchor drafts read the mask positions only, like DFlash
                const int32_t i_draft_beg = sample_from_anchor ? 0 : 1;
                for (int32_t i = i_draft_beg; i < n_block_tokens; ++i) {
                    const int32_t idx = beg + i;

                    if (conf && conf[(size_t) idx * n_embd_dec] < params.p_min) {
                        break;
                    }

                    common_sampler_sample(smpl, ctx_dft, idx, true);

                    const auto * cur_p = common_sampler_get_candidates(smpl, true);

                    for (int k = 0; k < std::min(3, (int) cur_p->size); ++k) {
                        LOG_DBG(" - seq_id %d, draft candidate %3d, pos %3d: %6d (%8.3f) '%s'\n",
                                seq_id, k, i, cur_p->data[k].id, cur_p->data[k].p,
                                common_token_to_piece(ctx_dft, cur_p->data[k].id).c_str());
                    }

                    const llama_token id = cur_p->data[0].id;

                    common_sampler_accept(smpl, id, true);

                    result.push_back(id);
                }
            } else {
                // greedily read the predicted block at this sequence's noise positions 1..n_block_tokens-1
                for (int32_t i = 1; i < n_block_tokens; ++i) {
                    common_sampler_sample(smpl, ctx_dft, beg + i, true);

                    const auto * cur_p = common_sampler_get_candidates(smpl, true);

                    for (int k = 0; k < std::min(3, (int) cur_p->size); ++k) {
                        LOG_DBG(" - seq_id %d, draft candidate %3d, pos %3d: %6d (%8.3f) '%s'\n",
                                seq_id, k, i - 1, cur_p->data[k].id, cur_p->data[k].p,
                                common_token_to_piece(ctx_dft, cur_p->data[k].id).c_str());
                    }

                    const llama_token id = cur_p->data[0].id;

                    if (cur_p->data[0].p < params.p_min) {
                        break;
                    }

                    common_sampler_accept(smpl, id, true);

                    result.push_back(id);
                }
            }

            if (result.size() < (size_t) params.n_min) {
                result.clear();
            }
        }
    }

    void accept(llama_seq_id /*seq_id*/, uint16_t /*n_accepted*/, bool /*is_other*/) override {
        // noop
    }
};

struct common_speculative_impl_draft_mtp : public common_speculative_impl {
    common_params_speculative_draft params; // reuses the draft-model params slot (ctx_tgt/ctx_dft)

    llama_batch batch;

    std::vector<common_sampler_ptr> smpls;

    // backend sampler chain per seq, attached to ctx_dft
    std::vector<llama_sampler *> backend_chains;

    int32_t n_embd = 0;

    // One MTP draft driver, three modes (set once in the ctor):
    //   is_mem_shared (gemma4): shares the target KV, runs all heads in one graph.
    //   chain_heads (step35): n_mtp_layers trained heads, one per draft step.
    //   neither (qwen35 / qwen35moe): a single trained MTP head.
    int32_t n_mtp_layers  = 1;
    bool    is_mem_shared = false;   // gemma4
    bool    chain_heads   = false;   // derived in the ctor: n_mtp_layers > 1 && !is_mem_shared
    int32_t n_chain       = 0;       // > 0: the whole draft round runs as one graph, see draft_chained()
    int32_t n_chain_host  = 0;       // > 0: a drafter over the target's cache (Gemma 4) runs its steps as one graph, the host accepting
    common_speculative_draft_notes notes;

    // a chained round replays the verify batch of every drafting sequence in one decode, launched in process() right
    // behind the verify when its inputs can come from the target's graph and from the host otherwise, see chain_launch()
    struct chain_seq {
        std::vector<llama_token> replay_tok;
        std::vector<llama_pos>   replay_pos;
        std::vector<float>       replay_h;               // the target's hidden rows of the replay
        int32_t                  replay_n      = 0;
        int32_t                  last_accepted = 0;
        bool                     started       = false;  // a chained decode ran for this request
        llama_pos                base          = 0;      // position of its replay row 0
        int32_t                  off           = 1;      // the anchor sits at base + n_acc + off
        llama_pos                expect        = -1;     // where the next verify batch starts, -1 when none is due
        bool                     defer_last    = false;  // the last batch was a verify batch this drafter did not decode
        int32_t                  col           = -1;     // its column in the chained decode in flight
        // a draft left on the device for the verify (llama_set_tokens_device_seq) holds placeholders until resolve_ids()
        // reads it; LLAMA_NO_DRAFT_HANDOFF=1 reads it before the verify is queued
        llama_tokens *           ids_result    = nullptr;
        int32_t                  ids_col       = -1;
        llama_pos                ids_n_past    = -1;
        // a round launched behind the last verify (chain_host_early): this sequence's column in it, and the verify's
        // first position; ids_early marks drafts handed on from such a round
        int32_t                  early_col     = -1;
        llama_pos                early_base    = -1;
        bool                     ids_early     = false;
    };
    std::vector<chain_seq> chain;
    bool chain_launched = false; // a chained decode no draft has taken yet is in flight

    // the round chain_host_early put behind the last verify, and how such rounds fared (LLAMA_ROUND_TIMING)
    bool        early_launched = false;
    llama_batch early_batch    = {};
    struct early_stats {
        int launched = 0, used = 0, fallback = 0, here = 0, stale = 0;
        void note() {
            static const bool on = getenv("LLAMA_ROUND_TIMING") != nullptr;
            if (on && (used + fallback) % 200 == 0 && used + fallback > 0) {
                fprintf(stderr, "[round] early drafts: launched %d, used %d, host fallback %d, anchors right %d, stale %d\n",
                        launched, used, fallback, here, stale);
            }
        }
    } early;

    std::vector<int32_t>             round_c; // the host route's inputs
    std::vector<float>               round_h;
    std::vector<llama_mtp_round_seq> round_seqs;

    void chain_reset(llama_seq_id seq) {
        auto & cs = chain[seq];
        cs.started    = false;
        cs.expect     = -1;
        cs.replay_n   = 0;
        cs.defer_last = false;
        cs.col        = -1;
        cs.early_col  = -1;
        chain_launched = false;
        for (const auto & c : chain) {
            chain_launched = chain_launched || c.col >= 0;
        }
    }

    // per sequence V replay rows, then the chain rows step by step; the device route takes the round's inputs from
    // the target's graph
    void chain_launch(const std::vector<llama_seq_id> & seqs, bool host_route, const common_speculative_draft_params_vec * dparams) {
        auto * ctx_dft = params.ctx_dft;
        auto * ctx_tgt = params.ctx_tgt;
        const int K = n_chain;
        const int V = n_chain + 1;
        const int S = (int) seqs.size();
        const size_t row_bytes = (size_t) n_embd * sizeof(float);

        common_batch_clear(batch);
        round_seqs.assign(S, llama_mtp_round_seq());
        if (host_route) {
            round_c.assign((size_t) S*V, -1);
            round_h.assign((size_t) S*V*n_embd, 0.0f);
        }
        for (int s = 0; s < S; ++s) {
            const llama_seq_id seq = seqs[s];
            auto & cs = chain[seq];
            auto & q  = round_seqs[s];
            q.seq_id = seq;
            if (host_route) {
                const auto & dp = (*dparams)[seq];
                const bool first = !cs.started || cs.replay_n == 0;
                // rows past the replay: never equal to what the round compares them with
                const llama_token junk = dp.id_last == 1 ? 2 : 1;
                int32_t * c = round_c.data() + (size_t) s*V;
                float   * h = round_h.data() + (size_t) s*V*n_embd;
                if (first) {
                    // nothing to replay: junk rows the chain never sees, the anchor at base
                    cs.base = dp.pos0;
                    for (int k = 0; k < V; ++k) {
                        common_batch_add(batch, k == 0 ? dp.id_last : junk, cs.base + k, { seq }, false);
                    }
                    c[0] = dp.id_last;
                    std::memcpy(h, pending_h[seq].data(), row_bytes);
                    q.h_pend = pending_h[seq].data();
                    q.off    = 0;
                } else {
                    cs.base = cs.replay_pos[0];
                    for (int k = 0; k < V; ++k) {
                        const bool real = k < cs.replay_n;
                        common_batch_add(batch, real ? cs.replay_tok[k] : junk,
                                real ? cs.replay_pos[k] : cs.replay_pos[cs.replay_n - 1] + (k - cs.replay_n + 1), { seq }, false);
                    }
                    for (int i = 0; i < K; ++i) {
                        c[i] = i < cs.last_accepted ? cs.replay_tok[i + 1] : -1;
                    }
                    c[std::min(cs.last_accepted, K)] = dp.id_last;
                    GGML_ASSERT(cs.replay_h.size() >= (size_t) cs.replay_n*n_embd);
                    std::memcpy(h, cs.replay_h.data(), row_bytes * cs.replay_n);
                    // replay row 0 pairs with the row the sequence's last round left on the device
                    q.h_pend = nullptr;
                    q.off    = 1;
                }
                q.c_ids = c;
                q.h_tgt = h;
            } else {
                cs.base = cs.replay_pos[0];
                for (int k = 0; k < V; ++k) {
                    common_batch_add(batch, cs.replay_tok[k], cs.replay_pos[k], { seq }, false);
                }
                q.off = 1;
                const bool ok = llama_get_last_rows(ctx_tgt, seq, cs.replay_pos[0], V, &q.tgt_row, &q.tgt_out);
                GGML_ASSERT(ok);
            }
            cs.off = q.off;
        }
        for (int j = 0; j < K; ++j) {
            for (int s = 0; s < S; ++s) {
                common_batch_add(batch, 0, chain[seqs[s]].base + V + j, { seqs[s] }, false);
            }
        }
        std::memset(batch.embd, 0, row_bytes * batch.n_tokens);

        for (int s = 0; s < S; ++s) {
            const auto & cs = chain[seqs[s]];
            SPC_DBG("chain_launch: seq %d host_route %d base %d replay_n %d last_accepted %d\n",
                    (int) seqs[s], (int) host_route, (int) cs.base, (int) cs.replay_n, (int) cs.last_accepted);
            // the cache goes back to base: the last round's chain and the replay rows it did not accept live there
            llama_memory_seq_rm(llama_get_memory(ctx_dft), seqs[s], cs.base, -1);
        }

        llama_set_mtp_round_seqs(ctx_dft, round_seqs.data(), S);
        llama_set_mtp_chain(ctx_dft, n_chain);
        llama_round_mark("chain.launch.begin", host_route);
        const int ret = llama_decode(ctx_dft, batch);
        llama_round_mark("chain.launch.end", ret);
        llama_set_mtp_chain(ctx_dft, 0);

        for (auto & c : chain) {
            c.col = -1;
        }
        if (ret != 0) {
            SPC_ERR("llama_decode(chained, n=%d, n_seq=%d) returned %d\n", n_chain, S, ret);
            chain_launched = false;
            return;
        }
        chain_launched = true;
        for (int s = 0; s < S; ++s) {
            auto & cs = chain[seqs[s]];
            cs.col      = s;
            cs.started  = true;
            cs.replay_n = 0;
        }
    }

    llama_context * ids_pending(llama_seq_id seq_id) const override {
        return seq_id >= 0 && seq_id < (llama_seq_id) chain.size() && chain[seq_id].ids_result != nullptr ? params.ctx_dft : nullptr;
    }

    bool arm_verify(llama_context * ctx_tgt, llama_seq_id seq_id, llama_pos pos0, int32_t n) override {
        if (ids_pending(seq_id) == nullptr) {
            return false;
        }
        return llama_set_tokens_device_seq(ctx_tgt, params.ctx_dft, seq_id, pos0, n, chain[seq_id].ids_col);
    }

    // The ids column col of the last chained decode drafted: written over result's placeholders (fill), or appended
    // when the round drafted for where the server is. False when the round drafted for a place the server has left.
    bool take_ids(const chain_seq & cs, int32_t col, llama_pos n_past, llama_tokens & result, bool fill) {
        const int K = n_chain;
        int32_t n_ids = 0;
        const llama_token * ids = llama_get_mtp_chain_ids(params.ctx_dft, &n_ids);
        const int32_t S = llama_get_mtp_chain_n_seq(params.ctx_dft);
        GGML_ASSERT(n_ids == (K + 1)*S && col >= 0 && col < S);
        const int32_t n_acc = ids[K*S + col];
        const bool here = n_past == cs.base + n_acc + cs.off;
        if (!here) {
            SPC_DBG("chained draft for a stale position: n_past %d, round expected %d\n", (int) n_past, (int) (cs.base + n_acc + cs.off));
        }
        if (fill) {
            // a draft cut short to what the request has left keeps the chain's first ids
            const size_t n = std::min<size_t>(K, result.size());
            for (size_t j = 0; j < n; ++j) {
                result[j] = ids[j*S + col];
            }
        } else if (here) {
            for (int j = 0; j < K; ++j) {
                result.push_back(ids[j*S + col]);
            }
        }
        return here;
    }

    // the ids of a round over the target's cache: K per sequence, a column each; a round launched behind the verify
    // (chain_host_early) has a row of accepted counts after them, which the host's acceptance should have matched
    void take_ids_host(const chain_seq & cs, int32_t col, llama_tokens & result) {
        const int K = n_chain_host;
        int32_t n_ids = 0;
        const llama_token * ids = llama_get_mtp_chain_ids(params.ctx_dft, &n_ids);
        const int32_t S = llama_get_mtp_chain_n_seq(params.ctx_dft);
        GGML_ASSERT((n_ids == K*S || n_ids == (K + 1)*S) && col >= 0 && col < S);
        if (n_ids == (K + 1)*S && cs.ids_early) {
            const int32_t n_acc = ids[K*S + col];
            const bool here = cs.ids_n_past == cs.early_base + n_acc + 1;
            if (here) {
                early.here++;
            } else {
                early.stale++;
                SPC_DBG("early draft for a stale anchor: n_past %d, round counted %d accepted from %d\n",
                        (int) cs.ids_n_past, (int) n_acc, (int) cs.early_base);
            }
        }
        const size_t n = std::min<size_t>(K, result.size());
        for (size_t j = 0; j < n; ++j) {
            result[j] = ids[j*S + col];
        }
    }

    bool resolve_ids(llama_seq_id seq_id) override {
        if (ids_pending(seq_id) == nullptr) {
            return false;
        }
        auto & cs = chain[seq_id];
        llama_tokens * result = cs.ids_result;
        cs.ids_result = nullptr;
        if (n_chain_host > 0) {
            take_ids_host(cs, cs.ids_col, *result);
            cs.ids_early = false;
            return true;
        }
        // drafted for a place the server has left, the verify took them on the device already and rejects them
        // like any other wrong guess
        take_ids(cs, cs.ids_col, cs.ids_n_past, *result, true);
        return true;
    }

    void resolve_all() {
        for (llama_seq_id seq_id = 0; seq_id < (llama_seq_id) chain.size(); ++seq_id) {
            resolve_ids(seq_id);
        }
    }

    void draft_chained(common_speculative_draft_params_vec & dparams) {
        resolve_all();
        const int K = n_chain;

        std::vector<llama_seq_id> want;
        std::vector<llama_seq_id> rest;
        for (llama_seq_id seq = 0; seq < (llama_seq_id) n_seq; ++seq) {
            auto & cs = chain[seq];
            if (!dparams[seq].drafting) {
                cs.expect = -1;
                continue;
            }
            want.push_back(seq);
            cs.expect = dparams[seq].pos0; // the next verify batch starts at the anchor, drafts or not
            if (!chain_launched || cs.col < 0) {
                rest.push_back(seq);
            }
        }
        if (want.empty()) {
            return;
        }

        if (!rest.empty()) {
            if (chain_launched) {
                // the decode in flight lacks some of them: its drafts are read back before a second decode
                for (llama_seq_id seq : want) {
                    const auto & cs = chain[seq];
                    if (cs.col >= 0) {
                        take_ids(cs, cs.col, dparams[seq].pos0, *dparams[seq].result, false);
                    }
                }
            }
            chain_launch(rest, true, &dparams);
            if (!chain_launched) {
                return;
            }
        }
        chain_launched = false;

        static const bool no_handoff = getenv("LLAMA_NO_DRAFT_HANDOFF") != nullptr;
        if (!no_handoff) {
            for (llama_seq_id seq : want) {
                auto & cs = chain[seq];
                if (cs.col < 0) {
                    continue;
                }
                auto & dp = dparams[seq];
                dp.result->insert(dp.result->end(), K, dp.id_last);
                cs.ids_result = dp.result;
                cs.ids_col    = cs.col;
                cs.ids_n_past = dp.pos0;
                cs.col        = -1;
            }
            return;
        }

        static struct spc_draft_timing {
            bool on = getenv("LLAMA_ROUND_TIMING") != nullptr;
            double ids = 0; int n = 0;
        } spct;
        const int64_t spc_t0 = spct.on ? ggml_time_us() : 0;
        for (llama_seq_id seq : want) {
            auto & cs = chain[seq];
            if (cs.col < 0) {
                continue;
            }
            // the round put the anchor after the rows it accepted; a server that
            // moved elsewhere (a restored checkpoint) gets no draft this time
            take_ids(cs, cs.col, dparams[seq].pos0, *dparams[seq].result, false);
            cs.col = -1;
        }
        if (spct.on) {
            spct.ids += (ggml_time_us() - spc_t0) / 1000.0;
            if (++spct.n % 100 == 0) {
                fprintf(stderr, "[round] draft phase n=%d  read ids %.3f ms per round\n", spct.n, spct.ids / spct.n);
            }
        }
    }

    // Per-sequence cross-batch carryover: pair (h_p, x_{p+1}) at MTP pos p+1.
    // The last h-row of one process() call needs the first token of the NEXT
    // call to pair with, so it's stashed here until that next call fires.
    std::vector<std::vector<float>> pending_h;   // [n_seq][n_embd]

    std::vector<int32_t> i_batch_beg;
    std::vector<int32_t> i_batch_end;

    // Hidden rows from the most recent target verification batch, grouped by seq.
    // Row 0 corresponds to the sampled token, row N to the Nth accepted draft token.
    std::vector<std::vector<float>> verify_h;
    std::vector<int32_t> verify_h_rows;
    // the rows left on the target (the step's last decode): their first batch row, the accepted row the next draft
    // anchors on, read back only when the device cannot take them (LLAMA_NO_EMBD_DEV=1 reads them back always)
    std::vector<int32_t> verify_h_beg;
    std::vector<bool>    verify_h_dev;
    std::vector<int32_t> pending_i_h;

    // LLAMA_NO_EMBD_DEV=1 reads the rows back after every verify
    bool leaves_rows() const override {
        static const bool no_embd_dev = getenv("LLAMA_NO_EMBD_DEV") != nullptr;
        return n_chain_host > 0 && !no_embd_dev;
    }

    std::vector<int>                i_last;
    std::vector<std::vector<float>> chain_h;

    common_speculative_impl_draft_mtp(const common_params_speculative & params, uint32_t n_seq)
        : common_speculative_impl(COMMON_SPECULATIVE_TYPE_DRAFT_MTP, n_seq, params.draft.n_max)
        , params(params.draft)
    {
        auto * ctx_tgt = this->params.ctx_tgt;
        auto * ctx_dft = this->params.ctx_dft;
        GGML_ASSERT(ctx_tgt && ctx_dft && "MTP requires ctx_tgt and ctx_dft to be set");

        n_embd = llama_model_n_embd_out(llama_get_model(ctx_dft));
        GGML_ASSERT(n_embd == llama_model_n_embd_out(llama_get_model(ctx_tgt)) &&
                "MTP input row width must match the target h_nextn width");
        n_mtp_layers = std::max(1, (int) llama_model_n_layer_nextn(llama_get_model(ctx_dft)));

        SPC_TRC("%s", "adding speculative implementation 'draft-mtp'\n");
        SPC_TRC("- n_max=%d, n_min=%d, p_min=%.2f, n_embd=%d, backend_sampling=%d\n", this->params.n_max, this->params.n_min, this->params.p_min, n_embd, (int) this->params.backend_sampling);
        SPC_TRC("- gpu_layers=%d, cache_k=%s, cache_v=%s, ctx_tgt=%s, ctx_dft=%s, devices=[%s]\n",
                this->params.n_gpu_layers,
                (this->params.cache_type_k == GGML_TYPE_COUNT ? "auto" : ggml_type_name(this->params.cache_type_k)),
                (this->params.cache_type_v == GGML_TYPE_COUNT ? "auto" : ggml_type_name(this->params.cache_type_v)),
                ctx_tgt ? "yes" : "no",
                ctx_dft ? "yes" : "no",
                common_speculative_get_devices_str(this->params.devices).c_str());

        const int32_t n_b = (int32_t) llama_n_batch(ctx_dft);
        batch = llama_batch_init(/*n_tokens=*/ n_b, /*embd=*/ n_embd, /*n_seq_max=*/ 1);
        // llama_batch_init allocates only one of token/embd; MTP needs both.
        // TODO: fix, how to call without malloc
        batch.token = (llama_token *) malloc(sizeof(llama_token) * n_b);

        smpls.resize(n_seq);
        for (auto & s : smpls) {
            common_params_sampling sparams;
            sparams.no_perf  = false;
            sparams.top_k    = 10;
            sparams.samplers = { COMMON_SAMPLER_TYPE_TOP_K };
            s.reset(common_sampler_init(llama_get_model(ctx_dft), sparams));
        }

        // offload draft sampling to the backend
        backend_chains.assign(n_seq, nullptr);
        if (this->params.backend_sampling) {
            for (llama_seq_id seq_id = 0; seq_id < (llama_seq_id) n_seq; ++seq_id) {
                llama_sampler * chain = llama_sampler_chain_init(llama_sampler_chain_default_params());
                llama_sampler_chain_add(chain, llama_sampler_init_top_k(10));

                if (!llama_set_sampler(ctx_dft, seq_id, chain)) {
                    SPC_WRN("backend offload failed for seq_id=%d; using CPU sampler\n", (int) seq_id);
                    llama_sampler_free(chain);
                    chain = nullptr;
                }
                backend_chains[seq_id] = chain;
            }
        }

        llama_set_embeddings_nextn(ctx_tgt, true, /*masked*/ false);
        llama_set_embeddings_nextn(ctx_dft, true, /*masked*/ true);

        is_mem_shared = llama_get_ctx_other(ctx_dft) == ctx_tgt;
        chain_heads   = n_mtp_layers > 1 && !is_mem_shared;

        // several sequences chain too: the server's batches hold each sequence's rows together in slot order, so a
        // split leaves the rows the drafts read the target's hidden state from where they were (a wrong row would
        // only lose acceptance, the verify keeps the output right). LLAMA_MTP_CHAIN_SEQS=0 drafts them on the host
        static const bool no_chain   = getenv("LLAMA_NO_MTP_CHAIN") != nullptr;
        static const bool chain_seqs = getenv("LLAMA_MTP_CHAIN_SEQS") == nullptr || atoi(getenv("LLAMA_MTP_CHAIN_SEQS")) != 0;
        const uint32_t n_round_rows = n_seq * (2*this->params.n_max + 1);
        const bool seqs_ok = n_seq == 1 || (chain_seqs &&
                n_round_rows <= llama_n_ubatch(ctx_dft) && n_round_rows <= llama_n_batch(ctx_dft));
        // over the target's cache every sequence's K rows go in one decode, sequence after sequence
        const uint32_t n_host_rows = n_seq * (uint32_t) this->params.n_max;
        if (!no_chain && is_mem_shared && n_host_rows <= llama_n_ubatch(ctx_dft) && n_host_rows <= llama_n_batch(ctx_dft) &&
                this->params.n_max >= 2 && llama_context_flash_attn(ctx_dft) &&
                llama_model_has_mtp_chain(llama_get_model(ctx_dft))) {
            n_chain_host = this->params.n_max;
            SPC_TRC("- chained drafting over the target's cache, n=%d\n", n_chain_host);
        }
        if (!no_chain && !chain_heads && !is_mem_shared && seqs_ok && this->params.n_max >= 2 &&
                llama_context_flash_attn(ctx_dft) &&
                llama_model_has_mtp_chain(llama_get_model(ctx_dft))) {
            n_chain = this->params.n_max;
            llama_set_mtp_round_target(ctx_dft, ctx_tgt);

            // backend sampling gives one output per sequence and a chained round needs n_max: read the logits back
            for (llama_seq_id seq_id = 0; seq_id < (llama_seq_id) backend_chains.size(); ++seq_id) {
                if (backend_chains[seq_id]) {
                    llama_set_sampler(ctx_dft, seq_id, nullptr);
                    llama_sampler_free(backend_chains[seq_id]);
                    backend_chains[seq_id] = nullptr;
                }
            }

            SPC_TRC("- chained drafting, n=%d, n_seq=%u\n", n_chain, n_seq);
        }
        chain.assign(n_seq, chain_seq());

        if (chain_heads) {
            this->params.n_max = std::min(this->params.n_max, n_mtp_layers);

            chain_h.assign(n_seq, {});
            for (auto & c : chain_h) {
                c.reserve((size_t) (this->params.n_max + 1) * n_embd);
            }
        }
        this->n_max = this->params.n_max;

        pending_h.assign(n_seq, std::vector<float>(n_embd, 0.0f));

        i_last.assign(n_seq, -1);
        i_batch_beg.assign(n_seq, -1);
        i_batch_end.assign(n_seq, -1);

        verify_h.assign(n_seq, {});
        verify_h_rows.assign(n_seq, 0);
        verify_h_beg.assign(n_seq, -1);
        verify_h_dev.assign(n_seq, false);
        pending_i_h.assign(n_seq, 0);
    }

    ~common_speculative_impl_draft_mtp() override {
        auto * ctx_dft = this->params.ctx_dft;
        for (llama_seq_id seq_id = 0; seq_id < (llama_seq_id) backend_chains.size(); ++seq_id) {
            if (backend_chains[seq_id] == nullptr) {
                continue;
            }
            if (ctx_dft) {
                llama_set_sampler(ctx_dft, seq_id, nullptr);
            }
            llama_sampler_free(backend_chains[seq_id]);
        }
        backend_chains.clear();

        if (batch.token != nullptr) {
            free(batch.token);
            batch.token = nullptr;
        }
        llama_batch_free(batch);
        if (early_batch.token != nullptr) {
            llama_batch_free(early_batch);
        }
    }

    void begin(llama_seq_id seq_id, const llama_tokens & prompt) override {
        const int32_t N = (int32_t) prompt.size();
        if (N <= 0) {
            return;
        }

        auto * ctx_dft = this->params.ctx_dft;
        const llama_pos pos_max = llama_memory_seq_pos_max(llama_get_memory(ctx_dft), seq_id);

        if (seq_id >= 0 && seq_id < (llama_seq_id) chain.size()) {
            chain_reset(seq_id);
        }

        if (pos_max < N - 1 && !is_mem_shared) {
            SPC_WRN("ctx_dft pos_max=%d < N-1=%d - "
                    "process() hook may not have run on every prefill ubatch "
                    "(need_embd / logits=1 on every prompt position?). "
                    "Drafts may degrade.\n",
                    (int) pos_max, N - 1);
        }
    }

    // A chained drafter replays a verify batch in its next round instead of decoding it here. Any other rows go
    // through the MTP layer now, and their sequences' rounds start over from the host.
    bool process_chained(const llama_batch & batch_in) {
        auto * ctx_tgt = this->params.ctx_tgt;
        auto * ctx_dft = this->params.ctx_dft;

        const int32_t n_tokens  = batch_in.n_tokens;
        const int     V         = n_chain + 1;
        const size_t  row_bytes = (size_t) n_embd * sizeof(float);

        std::vector<llama_seq_id> deferred;
        std::vector<bool>         is_deferred(n_seq, false);
        bool all_deferred = true;
        for (llama_seq_id seq = 0; seq < (llama_seq_id) n_seq; ++seq) {
            const int32_t beg = i_batch_beg[seq];
            if (beg < 0) {
                continue;
            }
            auto & cs = chain[seq];
            const int32_t n_rows = i_batch_end[seq] - beg + 1;
            bool ok = n_rows <= V && cs.expect >= 0 && batch_in.pos[beg] == cs.expect;
            for (int32_t k = beg; ok && k <= i_batch_end[seq]; ++k) {
                ok = batch_in.seq_id[k][0] == seq && batch_in.pos[k] == batch_in.pos[beg] + (k - beg);
            }
            if (!ok) {
                all_deferred = false;
                chain_reset(seq);
                continue;
            }
            // a verify batch: only its first token is the target's, the rest are drafts until accepted
            llama_draft_note_tokens(ctx_dft, seq, batch_in.token + beg, 1);
            cs.replay_tok.assign(batch_in.token + beg, batch_in.token + beg + n_rows);
            cs.replay_pos.assign(batch_in.pos   + beg, batch_in.pos   + beg + n_rows);
            cs.replay_n   = n_rows;
            cs.defer_last = true;
            cs.col        = -1;
            deferred.push_back(seq);
            is_deferred[seq] = true;
        }

        if (!all_deferred) {
            notes.process(ctx_dft, batch_in, this->params.n_max, &is_deferred);

            common_batch_clear(batch);

            // each row pairs with the target's hidden row of its sequence's row before it
            const float * h_tgt = llama_get_embeddings_nextn(ctx_tgt);
            std::vector<int32_t> prev(n_seq, -1);
            for (int k = 0; k < n_tokens; ++k) {
                const llama_seq_id seq = batch_in.seq_id[k][0];
                if (is_deferred[seq]) {
                    continue;
                }
                common_batch_add(batch, batch_in.token[k], batch_in.pos[k], { seq }, 0);
                const float * h_row = prev[seq] < 0 ? pending_h[seq].data() : h_tgt + (size_t) prev[seq] * n_embd;
                std::memcpy(batch.embd + (size_t) (batch.n_tokens - 1) * n_embd, h_row, row_bytes);
                prev[seq] = k;
            }

            // as in process(): the drafter's cache ends where the target's batch begins
            if (!is_mem_shared) {
                for (llama_seq_id seq = 0; seq < (llama_seq_id) n_seq; ++seq) {
                    if (i_batch_beg[seq] >= 0 && !is_deferred[seq] &&
                            llama_memory_seq_pos_max(llama_get_memory(ctx_dft), seq) >= batch_in.pos[i_batch_beg[seq]]) {
                        llama_memory_seq_rm(llama_get_memory(ctx_dft), seq, batch_in.pos[i_batch_beg[seq]], -1);
                    }
                }
            }

            const int32_t rc = llama_decode(ctx_dft, batch);
            if (rc != 0) {
                SPC_ERR("llama_decode(ctx_dft) failed rc=%d (pos=%d)\n", (int) rc, (int) batch_in.pos[0]);
                // the deferred sequences' replay_h was never filled
                for (llama_seq_id seq : deferred) {
                    chain_reset(seq);
                }
                return false;
            }

            for (llama_seq_id seq = 0; seq < (llama_seq_id) n_seq; ++seq) {
                if (i_batch_end[seq] < 0 || is_deferred[seq]) {
                    continue;
                }

                const int32_t n_rows = i_batch_end[seq] - i_batch_beg[seq] + 1;
                verify_h_rows[seq] = n_rows;
                verify_h[seq].resize((size_t) n_rows * n_embd);

                for (int32_t i = 0; i < n_rows; ++i) {
                    const float * h = llama_get_embeddings_nextn_ith(ctx_tgt, i_batch_beg[seq] + i);
                    std::memcpy(verify_h[seq].data() + (size_t) i * n_embd, h, row_bytes);
                }

                std::memcpy(pending_h[seq].data(), verify_h[seq].data() + (size_t) (n_rows - 1) * n_embd, row_bytes);
            }
        }

        if (deferred.empty()) {
            return true;
        }

        // the next round goes on the device right behind this verify when it holds every verify that was due
        // every verify that was due is in this batch; other rows (a prompt chunk in the same forward) went through
        // the drafter above and do not hold the device round back
        bool dev = !deferred.empty();
        for (llama_seq_id seq = 0; dev && seq < (llama_seq_id) n_seq; ++seq) {
            dev = chain[seq].expect < 0 || is_deferred[seq];
        }
        for (llama_seq_id seq : deferred) {
            const auto & cs = chain[seq];
            dev = dev && cs.started && cs.replay_n == V && llama_sampler_on_backend(ctx_tgt, seq) &&
                  llama_get_last_rows(ctx_tgt, seq, cs.replay_pos[0], V, nullptr, nullptr);
        }
        if (dev) {
            chain_launch(deferred, false, nullptr);
        }

        // the target's hidden rows of each replay: the anchor's for accept(), and a host round's inputs
        for (llama_seq_id seq : deferred) {
            auto & cs = chain[seq];
            const int32_t n_rows = (int32_t) cs.replay_tok.size();
            cs.replay_h.resize((size_t) n_rows * n_embd);
            for (int32_t i = 0; i < n_rows; ++i) {
                std::memcpy(cs.replay_h.data() + (size_t) i * n_embd, llama_get_embeddings_nextn_ith(ctx_tgt, i_batch_beg[seq] + i), row_bytes);
            }
        }

        return true;
    }

    bool process(const llama_batch & batch_in) override {
        resolve_all();
        if (batch_in.n_tokens <= 0) {
            return true;
        }

        // TODO: how to make it work with vision tokens?
        if (batch_in.token == nullptr || batch_in.embd != nullptr) {
            // the drafter never sees these positions, so a round started before
            // them must not be replayed across the gap
            for (llama_seq_id seq = 0; seq < (llama_seq_id) chain.size(); ++seq) {
                chain_reset(seq);
            }
            return true;
        }

        const int32_t n_tokens = batch_in.n_tokens;

        // remember the first and last batch index for each sequence
        std::fill(i_batch_beg.begin(), i_batch_beg.end(), -1);
        std::fill(i_batch_end.begin(), i_batch_end.end(), -1);

        for (int k = 0; k < n_tokens; ++k) {
            for (llama_seq_id seq_id = 0; seq_id < (llama_seq_id) n_seq; ++seq_id) {
                GGML_ASSERT(batch_in.n_seq_id[k] == 1);

                if (batch_in.seq_id[k][0] == seq_id) {
                    i_batch_end[seq_id] = k;
                    if (i_batch_beg[seq_id] < 0) {
                        i_batch_beg[seq_id] = k;
                    }
                }
            }
        }

        if (n_chain > 0) {
            return process_chained(batch_in);
        }

        auto * ctx_tgt = this->params.ctx_tgt;
        auto * ctx_dft = this->params.ctx_dft;

        const size_t row_bytes = (size_t) n_embd * sizeof(float);

        if (batch_in.token && batch_in.seq_id) {
            notes.process(ctx_dft, batch_in, this->params.n_max);
        }

        // if kv is shared with target (e.g Gemma4), then we can skip this catch-up decode
        if (!is_mem_shared) {
            common_batch_clear(batch);

            for (int k = 0; k < n_tokens; ++k) {
                common_batch_add(batch, batch_in.token[k], batch_in.pos[k], { batch_in.seq_id[k][0] }, 0);
            }

            // shift the tgt embeddings to the right by one position
            // assumes that the tokens in the batch are sequential for each sequence
            // i.e. we cannot have seq_id like this: [0, 0, 0, 1, 1, 0, 1, 1]
            //                                                       ^--- this is a problem
            // TODO:this is generally true, but would be nice to assert it
            {
                const float * h_tgt = llama_get_embeddings_nextn(ctx_tgt);
                std::memcpy(batch.embd + (size_t) 1 * n_embd, h_tgt, row_bytes * (n_tokens-1));
            }

            // fill the pending embeddings from a previous run
            auto set_h = [&](int idx, const float * h_row) {
                std::memcpy(batch.embd + (size_t) idx * n_embd, h_row, row_bytes);
            };

            for (llama_seq_id seq_id = 0; seq_id < (llama_seq_id) n_seq; ++seq_id) {
                if (i_batch_beg[seq_id] < 0) {
                    continue;
                }

                set_h(i_batch_beg[seq_id], pending_h[seq_id].data());
            }

            auto * mem_dft = llama_get_memory(ctx_dft);

            bool ok = true;
            for (int head = 0; head < n_mtp_layers; ++head) {
                // the drafter's cache ends where the target's batch begins: drafts of a round that ended with its
                // request (or any row the target dropped) would otherwise sit at the positions this batch writes
                // ref: https://github.com/ggml-org/llama.cpp/pull/24340/changes#r3413498544
                for (llama_seq_id seq_id = 0; seq_id < (llama_seq_id) n_seq; ++seq_id) {
                    if (i_batch_beg[seq_id] < 0) {
                        continue;
                    }
                    const llama_pos p0 = batch_in.pos[i_batch_beg[seq_id]];
                    if (chain_heads || llama_memory_seq_pos_max(mem_dft, seq_id) >= p0) {
                        llama_memory_seq_rm(mem_dft, seq_id, p0, -1);
                    }
                }
                if (chain_heads) {
                    llama_set_nextn_layer_offset(ctx_dft, head);
                }

                const int32_t rc = llama_decode(ctx_dft, batch);
                if (rc != 0) {
                    SPC_ERR("llama_decode(ctx_dft) head=%d failed rc=%d (pos=%d)\n",
                            head, (int) rc, (int) batch_in.pos[0]);
                    ok = false;
                    break;
                }
            }

            if (chain_heads) {
                llama_set_nextn_layer_offset(ctx_dft, 0); // restore default for non-draft decodes
            }
            if (!ok) {
                return false;
            }
        }

        for (llama_seq_id seq_id = 0; seq_id < (llama_seq_id) n_seq; ++seq_id) {
            if (i_batch_end[seq_id] < 0) {
                continue;
            }

            const int32_t n_rows = i_batch_end[seq_id] - i_batch_beg[seq_id] + 1;
            verify_h_rows[seq_id] = n_rows;
            verify_h_beg[seq_id]  = i_batch_beg[seq_id];

            // the step's last decode leaves its rows on the target until the next draft takes them there
            if (last_decode && leaves_rows()) {
                verify_h_dev[seq_id] = true;
                pending_i_h[seq_id]  = n_rows - 1;
                continue;
            }
            verify_h_dev[seq_id] = false;
            verify_h[seq_id].resize((size_t) n_rows * n_embd);

            for (int32_t i = 0; i < n_rows; ++i) {
                const float * h = llama_get_embeddings_nextn_ith(ctx_tgt, i_batch_beg[seq_id] + i);
                std::memcpy(verify_h[seq_id].data() + (size_t) i * n_embd, h, row_bytes);
            }

            std::memcpy(pending_h[seq_id].data(),
                    verify_h[seq_id].data() + (size_t) (n_rows - 1) * n_embd, row_bytes);
        }

        if (n_chain_host > 0 && last_decode && leaves_rows()) {
            chain_host_early(batch_in);
        }

        return true;
    }

    // vLLM's runner drafts the next round from the rejection sampler's output on the device before the host sees
    // either (gpu_model_runner: _sample, then propose_draft_token_ids from the padded batch, nothing read back), so the
    // host's acceptance and the next step's setup run while the GPU drafts. The same here: the round of a drafter over
    // the target's cache goes on the device right behind the verify. Its batch holds every outcome of the verify per
    // sequence (llama_set_mtp_dev_anchors) and the graph drafts from the one the target's samples give; draft() hands
    // those drafts to the next verify. LLAMA_NO_EARLY_DRAFT=1 drafts after the host's acceptance only.
    void chain_host_early(const llama_batch & batch_in) {
        static const bool off = getenv("LLAMA_NO_EARLY_DRAFT") != nullptr;
        early_launched = false;
        for (auto & cs : chain) {
            cs.early_col = -1;
        }
        if (off || n_chain_host <= 0) {
            return;
        }
        auto * ctx_tgt = params.ctx_tgt;
        auto * ctx_dft = params.ctx_dft;
        const int K = n_chain_host;
        const int V = K + 1;

        // the sequences whose rows are a verify: V of them at consecutive positions, all sampled on the device
        std::vector<llama_seq_id>        seqs;
        std::vector<llama_mtp_round_seq> rs;
        for (llama_seq_id seq = 0; seq < (llama_seq_id) n_seq; ++seq) {
            const int32_t beg = i_batch_beg[seq];
            if (beg < 0) {
                continue;
            }
            bool ok = i_batch_end[seq] - beg + 1 == V && llama_sampler_on_backend(ctx_tgt, seq);
            for (int32_t k = beg; ok && k < beg + V; ++k) {
                ok = batch_in.seq_id[k][0] == seq && batch_in.pos[k] == batch_in.pos[beg] + (k - beg);
            }
            llama_mtp_round_seq q;
            q.seq_id = seq;
            q.off    = 1;
            ok = ok && llama_get_last_rows(ctx_tgt, seq, batch_in.pos[beg], V, &q.tgt_row, &q.tgt_out);
            if (!ok) {
                continue;
            }
            seqs.push_back(seq);
            rs.push_back(q);
        }
        const int S = (int) seqs.size();
        // the whole round in one ubatch
        if (S < 2 || (uint32_t) (S*V) > llama_n_ubatch(ctx_dft) || (uint32_t) (S*V) > llama_n_batch(ctx_dft)) {
            return;
        }

        // row j of a sequence: the verify's token j at the position of the anchor had the target accepted j drafts
        if (early_batch.token == nullptr) {
            early_batch = llama_batch_init((int32_t) llama_n_batch(ctx_dft), 0, 1);
        }
        common_batch_clear(early_batch);
        for (int s = 0; s < S; ++s) {
            const int32_t beg = i_batch_beg[seqs[s]];
            for (int j = 0; j < V; ++j) {
                common_batch_add(early_batch, batch_in.token[beg + j], batch_in.pos[beg] + 1 + j, { seqs[s] }, false);
            }
        }

        llama_set_mtp_round_target(ctx_dft, ctx_tgt);
        llama_set_mtp_round_seqs(ctx_dft, rs.data(), S);
        llama_set_mtp_dev_anchors(ctx_dft, true);
        llama_set_mtp_chain(ctx_dft, K);
        // the verify's outputs go out before the round's work lands on the target's stream: the host reads them while
        // the round runs (LLAMA_NO_OUTPUTS_FENCE=1 waits for both)
        static const bool no_fence = getenv("LLAMA_NO_OUTPUTS_FENCE") != nullptr;
        if (!no_fence) {
            llama_outputs_fence(ctx_tgt);
        }
        llama_round_mark("early.launch.begin", S);
        const int ret = llama_decode(ctx_dft, early_batch);
        llama_round_mark("early.launch.end", ret);
        llama_set_mtp_chain(ctx_dft, 0);
        llama_set_mtp_dev_anchors(ctx_dft, false);
        if (ret != 0) {
            SPC_ERR("llama_decode(early round over the target's cache, n=%d, n_seq=%d) returned %d\n", K, S, ret);
            return;
        }
        // the target's next graph overwrites the rows this round copies: it waits for the round
        llama_order_after(ctx_tgt, ctx_dft);

        early_launched = true;
        early.launched++;
        for (int s = 0; s < S; ++s) {
            chain[seqs[s]].early_col  = s;
            chain[seqs[s]].early_base = batch_in.pos[i_batch_beg[seqs[s]]];
        }
    }

    // the round of a drafter over the target's cache: one decode of n_chain_host rows per drafting sequence, sequence
    // after sequence, all at the anchor's position, the anchor in each sequence's first row and every other row filled
    // on the device from the step before it; the ids come back together, step by step, a column per sequence
    void draft_chain_host(common_speculative_draft_params_vec & dparams) {
        auto * ctx_dft = params.ctx_dft;
        const int K = n_chain_host;
        const size_t row_bytes = (size_t) n_embd * sizeof(float);

        // ids of the last round nobody took (a request that ended) come back before the round's tensors go
        resolve_all();

        // the round launched behind the last verify drafted for every outcome the target could give: its drafts go to
        // the next verify when every drafting sequence is in it, the host drafts otherwise. A few sequences outside it
        // (a prompt that just ended: its last chunk was no verify) verify placeholder drafts this once and the rest
        // keep theirs, where a host round redrafted every sequence (a step in six, ~3 ms each).
        // LLAMA_NO_EARLY_PARTIAL=1 drafts on the host then.
        if (early_launched) {
            early_launched = false;
            int n_drafting = 0;
            int n_missing  = 0;
            for (llama_seq_id seq_id = 0; seq_id < (llama_seq_id) n_seq; ++seq_id) {
                if (!dparams[seq_id].drafting) {
                    continue;
                }
                n_drafting++;
                n_missing += chain[seq_id].early_col < 0 ? 1 : 0;
            }
            static const bool no_handoff_early = getenv("LLAMA_NO_DRAFT_HANDOFF") != nullptr;
            static const bool no_partial       = getenv("LLAMA_NO_EARLY_PARTIAL") != nullptr;
            const bool all     = n_missing == 0;
            const bool partial = !no_partial && n_missing > 0 && n_missing <= std::max(2, n_drafting/8) && n_missing < n_drafting;
            if (n_drafting > 0 && (all || partial) && !no_handoff_early) {
                for (llama_seq_id seq_id = 0; seq_id < (llama_seq_id) n_seq; ++seq_id) {
                    auto & dp = dparams[seq_id];
                    if (!dp.drafting) {
                        continue;
                    }
                    auto & cs = chain[seq_id];
                    if (cs.early_col < 0) {
                        // the placeholders are its draft, from the host: the verify rejects them like any wrong guess
                        dp.result->insert(dp.result->end(), K, dp.id_last);
                        continue;
                    }
                    dp.result->insert(dp.result->end(), K, dp.id_last);
                    cs.ids_result = dp.result;
                    cs.ids_col    = cs.early_col;
                    cs.ids_n_past = dp.pos0;
                    cs.ids_early  = true;
                    // the round gathered this anchor's hidden row already
                    verify_h_dev[seq_id] = false;
                }
                early.used++;
                early.note();
                return;
            }
            early.fallback++;
            early.note();
        }

        std::vector<llama_seq_id> seqs;
        // anchors left on the target: their sequence, the accepted token's position and the batch row
        std::vector<llama_seq_id> dev_seq;
        std::vector<llama_pos>    dev_pos;
        std::vector<int32_t>      dev_row;
        common_batch_clear(batch);
        for (llama_seq_id seq_id = 0; seq_id < (llama_seq_id) n_seq; ++seq_id) {
            auto & dp = dparams[seq_id];
            if (!dp.drafting) {
                continue;
            }
            seqs.push_back(seq_id);
            for (int j = 0; j < K; ++j) {
                common_batch_add(batch, j == 0 ? dp.id_last : 0, dp.pos0, { seq_id }, false);
                float * h = batch.embd + (size_t) (batch.n_tokens - 1) * n_embd;
                if (j == 0) {
                    if (verify_h_dev[seq_id]) {
                        dev_seq.push_back(seq_id);
                        dev_pos.push_back(dp.pos0 - 1);
                        dev_row.push_back(batch.n_tokens - 1);
                        std::memset(h, 0, row_bytes);
                    } else {
                        std::memcpy(h, pending_h[seq_id].data(), row_bytes);
                    }
                } else {
                    std::memset(h, 0, row_bytes);
                }
            }
        }
        if (seqs.empty()) {
            return;
        }
        if (!dev_seq.empty()) {
            std::vector<char> okc(dev_seq.size(), 0);
            llama_set_embd_device_rows(ctx_dft, params.ctx_tgt, dev_seq.data(), dev_pos.data(), (int32_t) dev_seq.size(), (bool *) okc.data());
            for (size_t i = 0; i < dev_seq.size(); ++i) {
                const llama_seq_id seq_id = dev_seq[i];
                verify_h_dev[seq_id] = false;
                if (okc[i]) {
                    continue;
                }
                // not on the target any more: the host copy, still the target's last output
                const float * hh = llama_get_embeddings_nextn_ith(params.ctx_tgt, verify_h_beg[seq_id] + pending_i_h[seq_id]);
                std::memcpy(pending_h[seq_id].data(), hh, row_bytes);
                std::memcpy(batch.embd + (size_t) dev_row[i] * n_embd, hh, row_bytes);
            }
        }

        llama_set_mtp_chain(ctx_dft, K);
        llama_round_mark("chain.launch.begin", 2);
        const int ret = llama_decode(ctx_dft, batch);
        llama_round_mark("chain.launch.end", ret);
        llama_set_mtp_chain(ctx_dft, 0);
        if (ret != 0) {
            SPC_ERR("llama_decode(chained over the target's cache, n=%d, n_seq=%d) returned %d\n", K, (int) seqs.size(), ret);
            return;
        }

        const int S = (int) seqs.size();

        // The ids stay on the device: the verify takes them there (llama_set_tokens_device_seq) and the host reads
        // them after it, when they have long been written, so the verify is queued before this round has run.
        // Placeholders stand in the draft until then. LLAMA_NO_DRAFT_HANDOFF reads them back now.
        static const bool no_handoff = getenv("LLAMA_NO_DRAFT_HANDOFF") != nullptr;
        if (!no_handoff) {
            for (int s = 0; s < S; ++s) {
                auto & dp = dparams[seqs[s]];
                auto & cs = chain[seqs[s]];
                dp.result->insert(dp.result->end(), K, dp.id_last);
                cs.ids_result = dp.result;
                cs.ids_col    = s;
                cs.ids_n_past = dp.pos0;
            }
            return;
        }

        int32_t n_ids = 0;
        const llama_token * ids = llama_get_mtp_chain_ids(ctx_dft, &n_ids);
        GGML_ASSERT(n_ids == K*S);
        for (int s = 0; s < S; ++s) {
            auto & result = *dparams[seqs[s]].result;
            for (int j = 0; j < K; ++j) {
                result.push_back(ids[j*S + s]);
            }
        }
    }

    void draft(common_speculative_draft_params_vec & dparams) override {
        auto & ctx_dft = params.ctx_dft;

        if (n_chain > 0) {
            draft_chained(dparams);
            return;
        }
        if (n_chain_host > 0) {
            draft_chain_host(dparams);
            return;
        }

        common_batch_clear(batch);

        // keep track of which sequences are still drafting
        int n_drafting = 0;
        std::vector<bool> drafting(n_seq);

        const size_t row_bytes = (size_t) n_embd * sizeof(float);

        for (llama_seq_id seq_id = 0; seq_id < (llama_seq_id) n_seq; ++seq_id) {
            auto & dp = dparams[seq_id];

            if (!dp.drafting) {
                continue;
            }

            n_drafting++;
            drafting[seq_id] = true;
            common_sampler_reset(smpls[seq_id].get());

            common_batch_add(batch, dp.id_last, dp.pos0, { seq_id }, true);
            std::memcpy(batch.embd + (size_t) (batch.n_tokens - 1) * n_embd, pending_h[seq_id].data(), row_bytes);

            i_last[seq_id] = batch.n_tokens - 1;

            if (chain_heads) {
                chain_h[seq_id].assign(pending_h[seq_id].begin(), pending_h[seq_id].end());
            }
        }

        int i = 0;

        while (n_drafting > 0) {
            // each step decodes under a different head, i.e. a different decoder layer, and
            // KV is per layer. process() filled this layer's KV only for positions < pos0
            // (prompt + accepted prefix) — nothing in the draft region yet. so reset the
            // draft region (the seq_rm lower bound is pos0, leaving the prompt KV intact)
            // and select head i so it rebuilds its own layer's KV there; decoding just the
            // latest token would leave its attention reading cells only another head wrote.
            if (chain_heads) {
                auto * mem_dft = llama_get_memory(ctx_dft);
                for (llama_seq_id seq_id = 0; seq_id < (llama_seq_id) n_seq; ++seq_id) {
                    if (drafting[seq_id]) {
                        llama_memory_seq_rm(mem_dft, seq_id, dparams[seq_id].pos0, -1);
                    }
                }
                llama_set_nextn_layer_offset(ctx_dft, i);
            }

            int ret = llama_decode(ctx_dft, batch);
            if (ret != 0) {
                SPC_ERR("llama_decode[%d] returned %d\n", i, ret);
                break;
            }

            // rebuild the batch for the next step: the growing-KV paths re-add only the
            // new token (the KV already holds the prefix), while chained heads re-add the
            // whole prefix at the next head. dropped sequences are simply not re-added.
            common_batch_clear(batch);

            for (llama_seq_id seq_id = 0; seq_id < (llama_seq_id) n_seq; ++seq_id) {
                if (!drafting[seq_id]) {
                    continue;
                }

                auto * smpl = smpls[seq_id].get();

                common_sampler_sample(smpl, ctx_dft, i_last[seq_id], true);
                const float * h_row = llama_get_embeddings_nextn_ith(ctx_dft, i_last[seq_id]);

                const auto * cur_p = common_sampler_get_candidates(smpl, true);

                for (int k = 0; k < std::min(3, (int) cur_p->size); ++k) {
                    SPC_DBG(" - seq_id %d, draft candidate %3d, pos %3d: %6d (%8.3f) '%s'\n",
                            seq_id, k, i, cur_p->data[k].id, cur_p->data[k].p,
                            common_token_to_piece(ctx_dft, cur_p->data[k].id).c_str());
                }

                // add drafted token for each sequence
                const llama_token id = cur_p->data[0].id;

                // only collect very high-confidence draft tokens
                if (cur_p->data[0].p < params.p_min) {
                    drafting[seq_id] = false;
                    n_drafting--;

                    continue;
                }

                common_sampler_accept(smpl, id, true);

                auto & dp = dparams.at(seq_id);
                auto & result = *dp.result;

                result.push_back(id);

                if (params.n_max <= (int) result.size()) {
                    drafting[seq_id] = false;
                    n_drafting--;
                    continue;
                }

                if (chain_heads) {
                    // ref: https://github.com/ggml-org/llama.cpp/pull/24340#discussion_r3448031546
                    chain_h[seq_id].insert(chain_h[seq_id].end(), h_row, h_row + n_embd);

                    const int n_rows = (int) result.size() + 1; // id_last + tokens drafted so far
                    for (int t = 0; t < n_rows; ++t) {
                        const llama_token tok = (t == 0) ? dp.id_last : result[t - 1];
                        common_batch_add(batch, tok, dp.pos0 + t, { seq_id }, t == n_rows - 1);
                        std::memcpy(batch.embd + (size_t) (batch.n_tokens - 1) * n_embd,
                                    chain_h[seq_id].data() + (size_t) t * n_embd, row_bytes);
                    }
                } else if (is_mem_shared) {
                    // note: with shared memory (e.g. Gemma4 assistants) we use the same position for all draft tokens
                    // ref: https://github.com/huggingface/transformers/blob/effde20942e3f82a1b97449f60b3a48c5ff96145/docs/source/en/model_doc/gemma4_assistant.md?plain=1#L36-L37
                    common_batch_add(batch, id, dp.pos0, { seq_id }, true);
                    std::memcpy(batch.embd + (size_t) (batch.n_tokens - 1) * n_embd, h_row, row_bytes);
                } else {
                    common_batch_add(batch, id, dp.pos0 + i + 1, { seq_id }, true);
                    std::memcpy(batch.embd + (size_t) (batch.n_tokens - 1) * n_embd, h_row, row_bytes);
                }

                i_last[seq_id] = batch.n_tokens - 1;
            }

            if (batch.n_tokens == 0) {
                break;
            }

            ++i;
        }

        if (chain_heads) {
            llama_set_nextn_layer_offset(ctx_dft, 0); // restore default for non-draft decodes
        }

        for (llama_seq_id seq_id = 0; seq_id < (llama_seq_id) n_seq; ++seq_id) {
            auto & dp = dparams[seq_id];
            if (!dp.drafting) {
                continue;
            }

            if (dp.result->size() < (size_t) params.n_min) {
                dp.result->clear();
            }
        }
    }

    void accept(llama_seq_id seq_id, uint16_t n_accepted, bool /*is_other*/) override {
        resolve_all();
        if (seq_id < 0 || seq_id >= (llama_seq_id) n_seq) {
            return;
        }

        if (!chain.empty()) {
            auto & cs = chain[seq_id];
            cs.last_accepted = n_accepted;
            if (cs.defer_last) {
                llama_draft_note_tokens(params.ctx_dft, seq_id, cs.replay_tok.data() + 1, std::min<int32_t>(n_accepted, cs.replay_n - 1));
                // a verify batch this drafter did not decode: the anchor's hidden
                // row is the target's row after the ones it accepted
                cs.defer_last = false;
                const int32_t n_rows = (int32_t) cs.replay_tok.size();
                const int32_t i_h    = std::min<int32_t>(n_accepted, n_rows - 1);
                std::memcpy(pending_h[seq_id].data(), cs.replay_h.data() + (size_t) i_h * n_embd, (size_t) n_embd * sizeof(float));
                return;
            }
        }

        notes.accept(params.ctx_dft, seq_id, n_accepted);

        const int32_t n_rows = verify_h_rows[seq_id];
        if (n_rows <= 0) {
            return;
        }

        const int32_t i_h = std::min<int32_t>(n_accepted, n_rows - 1);
        if (verify_h_dev[seq_id]) {
            pending_i_h[seq_id] = i_h;
            return;
        }
        const size_t row_bytes = (size_t) n_embd * sizeof(float);
        std::memcpy(pending_h[seq_id].data(), verify_h[seq_id].data() + (size_t) i_h * n_embd, row_bytes);
    }
};

